# ─────────────────────────── B-2 真机分支拒执行（打桩） ───────────────────────────
def 判B2() -> dict:
    桩, 原pg, 原clip = _记录桩(), getattr(器官_手, "pyautogui", None), sys.modules.get("pyperclip")
    原手 = None
    临时pyper = types.SimpleNamespace(copy=lambda s: 桩.调用.append(("clip", (s,), {})))
    try:
        器官_手.pyautogui = 桩
        sys.modules["pyperclip"] = 临时pyper
        态 = 共存态(用gpu=False)
        手 = 手器(态, 演练=False)                     # ★真机分支，但后端全被替换
        原手 = 手._自用32
        手._自用32 = 桩
        拍 = [0.0]
        局 = 许可令牌.令牌局(拍源=lambda: 拍[0])
        闸 = 许可令牌.令牌闸(局, 可逆=set())

        # ① 默认关：不装闸 ⇒ 直接执行（=既有行为），桩被调用
        手._执行键("点击", "左")
        n0 = len(桩.调用)
        # ② 装闸无令牌 ⇒ 拒，桩零增量
        手.令牌闸 = 闸
        手._执行键("点击", "左")
        手._滚轮(3)
        手._键入("abc")
        n1 = len(桩.调用)
        动 = 态.取动作()
        # ③ 签发合法令牌（**必须用 `器官_手` 的同一指纹格式**）⇒ 恰执行一次；再执行 ⇒ 重放被拒
        t = 局.签发(许可令牌.指纹_键("点击", "左"), 确认事件="确认:1")
        手._执行键("点击", "左")
        n2 = len(桩.调用)
        手._执行键("点击", "左")
        n3 = len(桩.调用)
        # ④ 滚轮令牌
        t2 = 局.签发(许可令牌.指纹_滚轮(3), 确认事件="确认:2")
        手._滚轮(3)
        n4 = len(桩.调用)
        案 = dict(默认关执行=(n0 == 1),
                  无令牌拒_零调用=(n1 == n0),
                  反馈含拒执行=any("拒执行" in str(x) for x in (动.get("反馈") or [])),
                  令牌拒计数=(int(动.get("令牌拒", 0)) == 1 and 闸.计["拒"] >= 3),
                  有令牌恰一次=(n2 == n1 + 1),
                  重放零增量=(n3 == n2),
                  滚轮令牌生效=(n4 == n3 + 1),
                  一次性=(局.令牌s[t.id].已用拍 is not None
                        and 局.令牌s[t2.id].已用拍 is not None))
        # ⑤ 闸故障 ⇒ fail-closed
        class _坏闸:
            def 放行(self, s):
                raise RuntimeError("闸坏")
        手.令牌闸 = _坏闸()
        n5 = len(桩.调用)
        手._执行键("点击", "左")
        案["闸故障拒"] = (len(桩.调用) == n5)
        return dict(通过=bool(all(案.values())), 逐项=案, 桩调用数=len(桩.调用),
                    局统计=局.统计表(),
                    说明="真机分支全程打桩（pyautogui/pyperclip/滚轮 dll 全替换），未真动鼠标键盘")
    finally:
        if 原pg is None:
            try:
                del 器官_手.pyautogui
            except AttributeError:
                pass
        else:
            器官_手.pyautogui = 原pg
        if 原clip is None:
            sys.modules.pop("pyperclip", None)
        else:
            sys.modules["pyperclip"] = 原clip


