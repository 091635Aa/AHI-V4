    序后 = E.生成序列_静态(种子环境训 + 11, 预热 + 训 + 1, 阶=2, 噪率=噪率训, 方向="后向")
    序后测 = E.生成序列_静态(种子环境主 + 11, 测 + 1, 阶=2, 噪率=噪率训, 方向="后向")
