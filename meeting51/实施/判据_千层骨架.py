# ═══════════════════════════════ 工具 ═══════════════════════════════
def 造序(种子, 噪率=噪率训, 阶=阶主, 方向="前向", 全长=None):
    长 = 预热 + 训 + 测 + 1 if 全长 is None else int(全长)
    return E.生成序列_静态(种子, 长, 阶=阶, 噪率=噪率, 方向=方向)


def 造核(轴=None, 开关=None, 种子偏=0):
    开 = dict(开关 or {})
    if η冻结 is not None and "η读出" not in 开:
        开["η读出"] = η冻结
    return M.千层核(D=D, 种子=种子模型 + int(种子偏), 轴=轴, 开关=开)


def 训练(核, 序, 预热拍=预热, 训拍=训):
    输入, 目标 = 序["输入"], 序["目标"]
    n = min(int(序["长度"]) - 1, int(预热拍) + int(训拍))
    for t in range(n):
        核.前向一拍(输入[t])
        if t >= int(预热拍):
            核.学一拍(目标[t])
    return 核


def 评(核, 序, 从=0, 拍=None):
    输入, 目标 = 序["输入"], 序["目标"]
    n = min(int(序["长度"]) - 1, int(从) + (int(拍) if 拍 is not None else 测))
    对 = 0
    总 = 0
    逐对 = np.zeros(核.轴["A"], dtype=np.int64)
    逐总 = np.zeros(核.轴["A"], dtype=np.int64)
    预列 = []
    真列 = []
    for t in range(int(从), n):
        果 = 核.前向一拍(输入[t])
        正 = (果["预测"] == 目标[t])
        逐对 += 正
        逐总 += 1
        对 += int(np.sum(正))
        总 += int(正.size)
        预列.append(果["预测"].copy())
        真列.append(目标[t].copy())
    逐 = 逐对 / np.maximum(1, 逐总)
    return dict(总=float(对) / max(1, 总), 逐分区=逐, 预测=np.stack(预列) if 预列 else np.zeros((0,)),
                目标=np.stack(真列) if 真列 else np.zeros((0,)))


