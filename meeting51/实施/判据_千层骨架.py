def 逐位同(a, b):
    return bool(np.array_equal(a, b))


def 扫导入(路径):
    名 = set()
    with open(路径, encoding="utf-8") as f:
        for 行 in f.read().splitlines():
            s = 行.strip()
            if s.startswith("import "):
                名.add(s[len("import "):].split()[0].split(",")[0].split(".")[0])
            elif s.startswith("from "):
                名.add(s[len("from "):].split()[0].split(".")[0])
    return sorted(名)


def 源码(路径):
    with open(路径, encoding="utf-8-sig") as f:
        return f.read()


# ═══════════════════════════════ 扫描（预声明区间；训练/验证段上扫后冻结） ═══════════════════════════════
def 扫描(记录):
    global η冻结
    行 = []
    序训 = 造序(种子环境训, 噪率=噪率训, 全长=预热 + 训 + 1)
    for η in η扫描区间:
        核 = 造核(轴=dict(B=1), 开关=dict(η读出=η))
        训练(核, 序训)
        验 = 评(核, 序训, 从=预热 + 1, 拍=120)               # 训练段尾部作验证（同分布、未参与测试）
        行.append(dict(η=float(η), 验证准确率=float(验["总"])))
    最佳 = max(行, key=lambda r: r["验证准确率"])
    η冻结 = float(最佳["η"])
    记录["扫描"] = dict(η读出_区间=list(η扫描区间), η读出_选定=η冻结, 行=行,
                         竞争模式_区间=list(竞争扫描区间), 竞争模式_选定="全局",
                         τ档_选定=list(τ档冻结), ζ_选定=ζ冻结, K_选定=K冻结, λ_e_选定=λ_e冻结,
                         纪律="区间先声明；在训练/验证段上扫，测试段只评一次；选定后全文冻结")
    return 记录["扫描"]


