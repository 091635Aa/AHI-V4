# ═══════════════════════════════ 步4：轴D 时档（丙4 参考系） ═══════════════════════════════
def 步4(臂, 缓存):
    def 记(名, 通过, 实测, 阈值, 说明=""):
        臂[名] = dict(实测=实测, 阈值=阈值, 通过=bool(通过), 说明=说明, 步="步4")

    序主 = 造序(种子环境主)
    序迁 = 造序(种子环境迁, 噪率=噪率迁, 全长=测 + 1)
    核 = 造核()
    训练(核, 序主)
    快 = 快照(核)
    g前 = 核.容器.g.copy()

    # 参考系：provenance 调制可塑率；继续经历 150 拍（学读出+g 可塑）
    核.开关["g学"] = True
    训练(核, 序主, 预热拍=0, 训拍=150)
    g后 = 核.容器.g.copy()
    漂移 = np.mean(np.abs(g后 - g前), axis=1).ravel()           # 每单元漂移
    pro = 核.容器.pro.copy()
    阈高 = float(np.quantile(pro, 0.75))
    阈低 = float(np.quantile(pro, 0.25))
    高 = 漂移[pro >= 阈高]
    低 = 漂移[pro <= 阈低]
    比 = float(np.mean(高)) / max(1e-9, float(np.mean(低)))

    # 反例：全局统一 η（把所有 pro 抹成均值 ⇒ η_u 相同）⇒ 稳定性与适应性同时下降
    核2 = 恢复(造核(), 快)
    核2.开关["g学"] = True
    pro均值 = float(np.mean(核2.容器.pro))
    核2.容器.pro = np.full_like(核2.容器.pro, pro均值)
    g前2 = 核2.容器.g.copy()
    训练(核2, 序主, 预热拍=0, 训拍=150)
    漂移2 = np.mean(np.abs(核2.容器.g - g前2), axis=1).ravel()
    高2 = 漂移2[pro >= 阈高]
    低2 = 漂移2[pro <= 阈低]
    比2 = float(np.mean(高2)) / max(1e-9, float(np.mean(低2)))

    # 双分离：参考系应 = 高 pro 单元**稳**（漂移小）+ 低 pro 单元**可塑**（漂移大）；
    # 反例（全局统一 η）把这一分离压平：高 pro 反而更漂（稳定性↓）、低 pro 更僵（可塑性/适应性↓）。
    高参 = float(np.mean(高))
    低参 = float(np.mean(低))
    高统 = float(np.mean(高2))
    低统 = float(np.mean(低2))
    稳定比 = 高统 / max(1e-12, 高参)
    可塑比 = 低统 / max(1e-12, 低参)
    记("丙4_参考系稳定化",
       (比 <= 丙4_高pro漂移比_max) and (稳定比 >= 丙4_反例稳定比_min)
       and (可塑比 <= 丙4_反例可塑比_max),
       dict(高pro漂移=高参, 低pro漂移=低参, 漂移比=比,
            统一η_高pro漂移=高统, 统一η_低pro漂移=低统, 统一η_漂移比=比2,
            反例稳定比=稳定比, 反例可塑比=可塑比, pro均值=pro均值,
            高pro阈=阈高, 低pro阈=阈低, 训练后续经历拍=150),
       dict(高pro漂移比_max=丙4_高pro漂移比_max, 反例稳定比_min=丙4_反例稳定比_min,
            反例可塑比_max=丙4_反例可塑比_max),
       "η_u = η_0·(1−pro_u) ⇒ 高 pro 稳、低 pro 可塑（双分离）；反例=全局统一 η ⇒ "
       "稳定性（高 pro 更漂）与可塑性/适应性（低 pro 更僵）同时下降")
    return 臂


