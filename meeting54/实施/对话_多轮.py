def 回(器, 包, 历史, 用户话, 种子=54001, 温度=0.7):
    消息 = [dict(role="system", content="你是%s。用第一人称口语回答，简短自然（1–3 句），不要括号动作/表情，不要解释你是 AI。"
               % str(包.get("角色", "角色")))]
    消息 += 历史
    消息.append(dict(role="user", content=用户话))
    提示 = 器.分词器.apply_chat_template(消息, tokenize=False, add_generation_prompt=True)
    输入 = 器.分词器(提示, return_tensors="pt").to(器.设备)
    torch.manual_seed(int(种子))
    参 = dict(max_new_tokens=96, do_sample=True, temperature=float(温度), top_p=0.9, top_k=50,
              repetition_penalty=1.12, pad_token_id=器.分词器.eos_token_id)
    with torch.no_grad():
        out = 器.模型.generate(**输入, **参)
    文 = 器.分词器.decode(out[0][输入["input_ids"].shape[1]:], skip_special_tokens=True).strip()
    文 = LLM._收句(文, 最少字=4, 最多句=3)
    器.台账["调用"] += 1
    器.台账["生成字"] += len(文)
    return 文


