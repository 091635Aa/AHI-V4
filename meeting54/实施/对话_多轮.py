def 跑对话(器, 包, 记录, 历史, 起始="Q1", 轮数=8, 种子基=54001, 用历史=True):
    qid = 起始
    轮 = 0
    序号 = 0
    while qid and qid in 脚本 and 轮 < 轮数:
        项 = 脚本[qid]
        问 = 项["问"]
        答 = 回(器, 包, 历史 if 用历史 else [], 问, 种子=种子基 + 序号)
        分支 = "兜底"
        下一 = 项["兜底"]
        for 关键词, 目标 in 项.get("分支", []):
            if any(k in 答 for k in 关键词):
                分支 = "→".join(关键词)
                下一 = 目标
                break
        记录.append(dict(轮=轮 + 1, 问题=问, 回答=答, 命中分支=分支, 下一问=下一,
                         历史条数=len(历史) if 用历史 else 0))
        if 用历史:
            历史.append(dict(role="user", content=问))
            历史.append(dict(role="assistant", content=答))
        qid = 下一
        轮 += 1
    return 记录


def 上下文探针(器, 包, 记录, 历史, 种子=54999, 用历史=True):
    首问 = 记录[0]["问题"]
    首答 = 记录[0]["回答"]
    中间 = " ".join(x["问题"] for x in 记录[1:4])
    探针 = [
        ("P1", "我们最开始聊的第一件事是什么？我第一个问题问的是什么？"),
        ("P2", "你第一句是怎么回答我的？还记得吗？"),
        ("P3", "中间我提过谁的名字吗？"),
    ]
    行 = []
    for 名, 问 in 探针:
        答 = 回(器, 包, 历史 if 用历史 else [], 问, 种子=种子)
        行.append(dict(探针=名, 问=问, 答=答))
    return 行, 首问, 首答


