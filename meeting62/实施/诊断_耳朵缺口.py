def _读(path: str):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _r(x, n=6):
    return round(float(x), n)


# ─────────────────────────── (a) E5 冲突 ───────────────────────────
def 分析E5() -> dict:
    判v6 = _读(os.path.join(M61产物, "判据", "判据_发音_v6.json"))
    判v5 = _读(os.path.join(M61产物, "判据", "判据_发音_v5.json"))
    e5v6 = 判v6["臂"]["E5_谱形贴近参考"]["读数"]
    e5v5 = 判v5["臂"]["E5_谱形贴近参考"]["读数"]

    合成v6 = {k: float(e5v6["合成带"][k]) for k in 带名}
    合成v5 = {k: float(e5v5["合成带"][k]) for k in 带名}
    均值 = {k: float(e5v6["参考带均值"][k]) for k in 带名}
    范围 = {k: [float(x) for x in e5v6["参考带范围"][k]] for k in 带名}

    # 逐带：参考离散度（max/min）、合成到均值的绝对差
    逐带 = {}
    L1核对v6 = 0.0
    L1核对v5 = 0.0
    for k in 带名:
        lo, hi = 范围[k]
        比值 = (hi / lo) if lo > 0 else float("inf")
        差v6 = abs(合成v6[k] - 均值[k])
        差v5 = abs(合成v5[k] - 均值[k])
        L1核对v6 += 差v6
        L1核对v5 += 差v5
        逐带[k] = {
            "参考范围": [lo, hi],
            "参考离散度_max除min": _r(比值, 3),
            "合成v6": _r(合成v6[k], 4),
            "合成v6_到参考均值绝对差": _r(差v6, 4),
            "合成v5": _r(合成v5[k], 4),
            "合成v5_到参考均值绝对差": _r(差v5, 4),
            "合成v6_是否在参考范围内": bool(lo <= 合成v6[k] <= hi),
        }

    出范围 = [k for k in 带名 if not 逐带[k]["合成v6_是否在参考范围内"]]
    离散度 = [逐带[k]["参考离散度_max除min"] for k in 带名]

    return {
        "[实测]": True,
        "臂定义": "带分布 L1 = Σ_band |合成带分布 − 参考带分布均值|；参考=每角色第1个歌唱/清唱录音，共11文件",
        "v6读数": {"通过": bool(判v6["臂"]["E5_谱形贴近参考"]["通过"]), "L1": _r(e5v6["带分布L1"], 4),
                   "Σ逐带差_核对": _r(L1核对v6, 4), "合成重心Hz": _r(e5v6["合成重心"], 1),
                   "参考重心均值Hz": _r(e5v6["参考重心均值"], 1)},
        "v5读数": {"通过": bool(判v5["臂"]["E5_谱形贴近参考"]["通过"]), "L1": _r(e5v5["带分布L1"], 4),
                   "Σ逐带差_核对": _r(L1核对v5, 4)},
        "逐带": 逐带,
        "参考离散度_最大比值": _r(max(离散度), 3),
        "参考离散度_最小比值": _r(min(离散度), 3),
        "合成v6_落在参考范围外的频带": 出范围,
        "缺口判定": {
            "结论": "E5 锚定的是『11 个歌唱/清唱录音的带分布均值』，而该参考自身同一频带的 min/max 相差 "
                    "%s–%s 倍 ⇒ 带分布不是『正确发音』的稳定属性。" % (_r(min(离散度), 2), _r(max(离散度), 2)),
            "方向冲突": "v6 为把谱峰拉回 F1（元音身份）必然把能量从 0-500 移到 500-1000，"
                        "这正是 E5 记为差的方向；v5 之所以过 E5 部分靠『F1 区被低频平台让位』。",
            "结论_该臂有效性": "该臂不能当作『耳听满意』的门；它可当『是否像某几个参考录音』的相似度参考。",
        },
    }


# ─────────────────────────── (b) 音色身份可分 ───────────────────────────
# 12 标量 + 3 元组 = 共 14 维；值域取自 meeting58/实施/接口契约_角色声线.py 的 声线参数域
声线参数域 = {
    "基频": (70.0, 400.0), "语速": (1.5, 7.0), "幅度": (0.1, 1.0),
    "气声度": (0.0, 0.8), "紧喉度": (0.0, 1.0), "粗糙度": (0.0, 1.0),
    "送气量": (0.0, 1.0), "声区": (0.0, 1.0),
    "谱倾斜": (-0.85, 0.85), "气声谱重心": (0.0, 1.0), "抖动": (0.0, 1.0),
}
缩放域 = (0.70, 1.30)


def _向量(档案: dict) -> dict:
    v = {}
    for k in ("基频", "语速", "幅度", "气声度", "紧喉度", "粗糙度", "送气量", "声区", "谱倾斜", "气声谱重心", "抖动"):
        v[k] = float(档案[k])
    s = list(档案["共振峰缩放"])
    v["共振峰缩放1"], v["共振峰缩放2"], v["共振峰缩放3"] = float(s[0]), float(s[1]), float(s[2])
    return v


def _域(name: str) -> tuple:
    if name.startswith("共振峰缩放"):
        return 缩放域
    return 声线参数域[name]


def 维序():
    return ["基频", "语速", "幅度", "气声度", "紧喉度", "粗糙度", "送气量", "声区",
            "共振峰缩放1", "共振峰缩放2", "共振峰缩放3", "谱倾斜", "气声谱重心", "抖动"]


def 分析音色身份() -> dict:
    角色 = ["洛天依", "SpeakerA", "EmoCompanion"]
    档案 = {}
    for n in 角色:
        档案[n] = _读(os.path.join(M61产物, "声线档案", n + ".json"))
    vec = {n: _向量(档案[n]) for n in 角色}
    dims = 维序()

    # 每维跨角色极差
    跨角色 = {}
    for d in dims:
        vals = [vec[n][d] for n in 角色]
        lo_hi = _域(d)
        极差 = max(vals) - min(vals)
        跨角色[d] = {"值": {n: _r(vec[n][d], 6) for n in 角色},
                     "极差": _r(极差, 6),
                     "归一极差_除值域宽": _r(极差 / (lo_hi[1] - lo_hi[0]), 6),
                     "零极差": bool(极差 == 0.0)}

    恒同维 = [d for d in dims if 跨角色[d]["零极差"]]
    变维 = [d for d in dims if not 跨角色[d]["零极差"]]

    # 两两：契约值域归一后的 L2 距离 + F0 半音距离
    def 归一距(a, b):
        s = 0.0
        for d in dims:
            lo_hi = _域(d)
            s += ((vec[a][d] - vec[b][d]) / (lo_hi[1] - lo_hi[0])) ** 2
        return math.sqrt(s)

    def 半音(a, b):
        return 12.0 * math.log2(vec[a]["基频"] / vec[b]["基频"])

    两两 = {}
    for i in range(len(角色)):
        for j in range(i + 1, len(角色)):
            a, b = 角色[i], 角色[j]
            两两["%s-%s" % (a, b)] = {
                "契约值域归一L2距离": _r(归一距(a, b), 4),
                "F0半音距_档案层": _r(半音(a, b), 3),
            }

    # 参考层 F0 半音（来源：指标/拟合44_*.json）
    参考F0 = {}
    for n in 角色:
        拟合 = _读(os.path.join(M61产物, "指标", "拟合44_%s.json" % n))
        参考F0[n] = float(拟合["参考统计"]["F0中位"])
    参半音 = {}
    for i in range(len(角色)):
        for j in range(i + 1, len(角色)):
            a, b = 角色[i], 角色[j]
            参半音["%s-%s" % (a, b)] = _r(12.0 * math.log2(参考F0[a] / 参考F0[b]), 3)

    # 阈值判定（[提案]，未盲评验证）
    阈值 = {
        "L2距离_判听不出": 0.20,
        "F0半音_判听不出": 1.0,
        "口径": "[提案] 契约值域归一 L2 < 0.20 且 F0 半音 < 1.0 ⇒ 判『换角色听不出』；"
                "两条件任一越阈 ⇒ 判『可能听得出（待真人 A/B 验证）』。阈值未盲评标定。",
        "标注": "[提案]",
    }
    判定 = {}
    for k, v in 两两.items():
        d = v["契约值域归一L2距离"]
        st = abs(v["F0半音距_档案层"])
        能听 = (d >= 阈值["L2距离_判听不出"]) or (st >= 阈值["F0半音_判听不出"])
        判定[k] = {
            "L2": d, "F0半音": v["F0半音距_档案层"],
            "判定": "可能听得出（待验证）" if 能听 else "判听不出",
        }

    return {
        "[实测]": True,
        "契约维定义": "meeting58/实施/接口契约_角色声线.py ＋ meeting58/最终方案.md §2.3（1-8 基频/语速/幅度/气声度/紧喉度/粗糙度/送气量/声区；9-11 共振峰缩放；12 谱倾斜；13 气声谱重心；14 抖动）",
        "维数": len(dims),
        "恒同维": 恒同维,
        "恒同维数": len(恒同维),
        "可变维": 变维,
        "可变维数": len(变维),
        "跨角色各维": 跨角色,
        "两两_档案层": 两两,
        "两两_参考F0半音": 参半音,
        "参考F0中位": {n: _r(参考F0[n], 2) for n in 角色},
        "阈值": 阈值,
        "判定": 判定,
        "缺口判定": {
            "结论": "14 维中 %d 维在三角色间逐位恒同（语速/幅度/紧喉/送气/谱倾斜/气声谱重心/共振峰缩放第1轴），"
                    "剩余 %d 维差异极小；主张的『声道尺度(共振峰缩放)是角色差异主维度』在档案层已塌缩"
                    "（洛[1.1,1.1,1.1] vs 登/缘[1.1,1.044,1.044]）。" % (len(恒同维), len(变维)),
            "参考层_可辨": ("参考录音层 F0 中位 %s–%s Hz（半音距 %s–%s），"
                            "共振峰 F3 差约 23%% ⇒ 原始参考是可分的。"
                            % (_r(min(参考F0.values()), 1), _r(max(参考F0.values()), 1),
                               _r(min(参半音.values()), 2), _r(max(参半音.values()), 2))),
            "档案层_塌缩": "拟合把可分的参考压成近乎同值的档案 ⇒ 引擎对三角色产出的可听差异主要只剩 F0(基频)。",
            "待验证": "判定阈值 [提案]，须真人 A/B 盲评（三角色同句辨识率 vs 机会 1/3）才可定论——未测。",
        },
    }


