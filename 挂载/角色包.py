def 全部包() -> dict:
    return {"洛天依": 建_洛天依(), "MOSS": 建_MOSS(), "日记角色": 建_日记角色()}


def 导出(目录: str = None) -> list:
    目录 = 目录 or 包目录
    os.makedirs(目录, exist_ok=True)
    路径列 = []
    for 名, 包 in 全部包().items():
        p = os.path.join(目录, "%s.json" % 名)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(包, f, ensure_ascii=False, indent=1)
        路径列.append(p)
    return 路径列


