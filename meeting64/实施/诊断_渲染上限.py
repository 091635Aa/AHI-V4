def _f(x, _n=4) -> str:
    """布尔 → ✓/✗；None → —；其余原样。"""
    if x is None:
        return "—"
    if isinstance(x, bool):
        return "✓" if x else "✗"
    return str(x)


def _f4(x) -> str:
    return "—" if x is None else "%.4f" % x


def _fΔ(x) -> str:
    return "—" if x is None else "%+.4f" % x


