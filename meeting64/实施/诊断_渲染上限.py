# ══════════════════════ 评一个条件 × 一个集合 ══════════════════════
def 评(引: dict, 参数: dict, 标签: str, 句集, 条件号: int, 趟数: int = 1) -> dict:
    """合成 句集 × 角色s → 每样本 趟数 次转写 → CER/对齐/峰值/音节率。

    ★ 波形与 `量具_v9.合成多句` 完全同一路径（造档案 → 韵律工厂(档,种子).说 → 写wav），
      句集用 `句集入` 覆盖；样本文名含 run_id（唯一）。
    """
    t0 = time.perf_counter()
    工厂 = H9.造(参数)
    临时 = os.path.join(临时根, 量._安全(标签))
    合 = 量.合成多句(工厂, 角色s=角色s, 标签=标签, 临时目录=临时, 种子=种子,
                     角色改=None, 句集入=tuple(句集), 条件号=int(条件号))
    逐样本 = {}
    一致 = True
    峰 = 0.0
    for 句号, 句 in 句集:
        音数 = _音节数(句)
        for 名 in 角色s:
            v = 合["样本"][(句号, 名)]
            读s = [引["转写"](v["路径"]) for _ in range(int(趟数))]
            t1 = 读s[0]
            同 = bool(all(t == t1 for t in 读s))
            if not 同:
                一致 = False
                print("[多趟不一致] %s·%s·%s「%s」≠「%s」" % (标签, 句号, 名, t1, 读s), flush=True)
            cer = 量.CER(句, t1)
            峰 = max(峰, _读峰值(v["路径"]))
            逐样本["%s·%s" % (句号, 名)] = dict(
                句号=句号, 句=句, 角色=名, wav=v["wav"], sha256=v["sha256"],
                时长秒=v["时长秒"], 音节数=音数,
                音节率=round(音数 / v["时长秒"], 3) if v["时长秒"] > 0 else 0.0,
                转写=t1, 转写各趟=读s, 趟一致=同, CER=cer, 对齐=量.对齐(句, t1),
            )
            print("[评] %-18s %-9s CER=%.3f「%s」" % (标签, "%s·%s" % (句号, 名), cer, t1), flush=True)

    逐句均值 = {句号: round(float(np.mean([逐样本["%s·%s" % (句号, n)]["CER"] for n in 角色s])), 4)
                for 句号, _ in 句集}
    逐角色均值 = {名: round(float(np.mean([逐样本["%s·%s" % (句号, 名)]["CER"] for 句号, _ in 句集])), 4)
                 for 名 in 角色s}
    均值 = round(float(np.mean([v["CER"] for v in 逐样本.values()])), 4)
    总音节 = int(sum(v["音节数"] for v in 逐样本.values()))
    总时长 = float(sum(v["时长秒"] for v in 逐样本.values()))
    音率 = round(总音节 / 总时长, 3) if 总时长 > 0 else 0.0
    每样本音率 = sorted(v["音节率"] for v in 逐样本.values())
    return dict(
        标签=标签, 参数={k: float(v) for k, v in 参数.items()},
        集合名=("筛选" if 句集 is 筛选 else ("留出" if 句集 is 留出 else "其他")),
        条件号=int(条件号), 趟数=int(趟数),
        逐样本=逐样本, 逐句均值=逐句均值, 逐角色均值=逐角色均值, CER均值=均值,
        峰值=round(峰, 4), 总音节=总音节, 总时长秒=round(总时长, 3), 音节率=音率,
        音节率区间=[每样本音率[0], 每样本音率[-1]],
        音节率达标=bool(音率门槛[0] <= 音率 <= 音率门槛[1]),
        峰值超1=bool(峰 > 1.0), 两趟一致=bool(一致),
        临时目录=合["目录"], run_id=合["run_id"], 音色指纹={k: v for k, v in 合["角色音色s"].items()},
        耗时秒=round(time.perf_counter() - t0, 2),
    )


# ══════════════════════ 校准：真人 → ASR → 同角色 v8.1 合成 → ASR ══════════════════════
def 校准(引: dict) -> list:
    临时 = os.path.join(临时根, "校准")
    os.makedirs(临时, exist_ok=True)
    表 = []
    for 名, 路 in 校准对:
        项 = dict(角色=名, 真人wav=路)
        if not os.path.exists(路):
            项["缺失"] = True
            表.append(项)
            continue
        t0 = time.perf_counter()
        T_h = 引["转写"](路)
        if not str(T_h).strip():
            项.update(dict(真人转写="", 真人时长秒=_wav时长(路), 异常="ASR 对真人 wav 返回空文本"))
            表.append(项)
            print("[校准] %-4s 真人转写为空（跳过合成）" % 名, flush=True)
            continue
        真人秒 = _wav时长(路)
        音色 = 量.取音色([名])[名]
        档 = 量.造档案(音色)
        波形, _元, _帧 = H9.造({})(档, 种子).说(T_h)     # v8.1 默认（全中性）
        run = 量.新run_id()
        文 = "校准_%s_%s.wav" % (量._安全(名), run)
        路2 = os.path.join(临时, 文)
        量.写wav(路2, 波形)
        T_s = 引["转写"](路2)
        项.update(dict(
            真人转写=T_h, 真人时长秒=真人秒,
            合成wav=文, 合成时长秒=round(float(np.size(波形)) / FS, 3),
            合成转写=T_s, CER=量.CER(T_h, T_s), 对齐=量.对齐(T_h, T_s),
            合成峰值=round(float(np.max(np.abs(波形))) if np.size(波形) else 0.0, 4),
            耗时秒=round(time.perf_counter() - t0, 2),
        ))
        表.append(项)
        print("[校准] %-4s 真人「%s」\n       合成「%s」 CER=%.3f" % (名, T_h, T_s, 项["CER"]), flush=True)
    return 表


# ══════════════════════ 判定（机械规则） ══════════════════════
def 判定(筛选Δ: float, 留出Δ) -> str:
    if 筛选Δ > 筛选门槛:
        return "未过筛选（中性）" if 筛选Δ <= 0.03 else "未过筛选（更差）"
    if 留出Δ is None:
        return "过筛选·未评留出（异常）"
    if 留出Δ > 0.0:
        return "不可迁移（筛选小胜/留出变差 §8.6 同形）"
    if 留出Δ <= 留出门槛:
        return "可迁移"
    return "不可迁移（留出未达 −0.02）"


