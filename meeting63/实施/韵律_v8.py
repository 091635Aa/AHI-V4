"""meeting63/实施/韵律_v8.py —— 咬字修复版（在 韵律_v7 上按「内生耳+皮层」的诊断改）。

只读 import `meeting61/实施/音韵_v5.py`、`meeting62/实施/韵律_v7.py`、`引擎_v7`；
**不改 v5/v6/v7 一字**（C14）。除下列改动外，**与 韵律_v7 逐位同**。

诊断来源（真跑，见 `01_预检报告.md`）：
  · 预检_咬字（帧侧）：v7 塞音爆破=固定 10ms、擦音 60ms、VOT 送气 40ms；
    但 `耳_内生` 波形侧切段显示 v7 的清/浊段时长**与真人参考同量级** ⇒ 时长不是主因。
  · 皮层_音素格（波形侧·零外挂）：v7 留出音节分类 0.80（chance 0.20），**唯一残留混淆是
    「送气塞 p/t/k → 擦」2/2** ⇒ 合成塞音**没有可感知的除阻瞬态**（爆破被 40ms 送气淹没）。

改动（全部落在**辅音实现**，元音/声道参数一字不动）：
  ① **除阻爆破更短更冲**：爆破时长 0.008→`参数[爆破秒]`(5ms)；爆破幅度 ×`参数[爆幅倍]`(1.6)；
     `爆破带` 带宽收窄（900/1800/1200 → 500/900/700）⇒ 谱更集中、瞬态 crest 更高。
  ② **CV 转迹更强**：`终点混合` 0.45→0.30（辅音终点更贴 locus ⇒ 协同发音更明显）。
  ③ **CV 过渡更长**：元音起始过渡 30ms→`参数[过渡秒]`(45ms) ⇒ 滑移更可闻。
  ④ **辅音时长缩放下限**：`缩辅 = max(缩, 缩底=0.85)`（原 `缩`=3.2/语速，语速 4.8 ⇒ 0.667）
     ⇒ 辅音不再被过度压缩（**元音时长缩放 `缩` 不变**）。
  ⑤ **鼻尾全音节化（多句 ASR 实测驱动）**：鼻尾原先只在短语最后一个音节生成 ⇒「鼻尾·句中」错误率
     0.839；现改为**每个**带 -n/-ng 韵尾的音节都生成，且**从元音段借帧**（不追加帧、不拉长语速），
     包络由陡降改为持续型（原 6 帧里只前 2 帧有量）。

机器可搜参数（供 `学_咬字反馈.py` 做参考+反馈学习）：`参数`。
"""
