    塞擦爆破秒=0.004,    # 塞擦短爆破（v7=0.006）
    爆幅倍=1.6,          # 爆破幅度倍率（v7=1.0）
    终点混合=0.30,       # 辅音终点 = 轨 + (目−轨)·此值（v7=0.45）
    过渡秒=0.03,         # 元音起始 CV 过渡时长（学习结论：0.03 最可分）
    缩底=0.85,           # 辅音时长缩放下限（v7 无下限 = 3.2/语速）
