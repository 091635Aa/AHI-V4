class 人类韵律_v8(H7.人类韵律_v5):
    """文本 → 帧（v8：除阻瞬态强化 + CV 转迹增强 + 辅音时长下限 + 鼻尾全音节化）。"""

    def _缩辅(self) -> float:
        return float(max(self.缩, float(参数["缩底"])))

    def _清(self):
        """在既有帧字段上追加鼻零极点三列（默认 0 ⇒ 与 v5/v7 逐位同）。"""
        super()._清()
        for _k in ("鼻增益", "鼻极", "鼻零"):
            self.帧[_k] = []

    def _加(self, f0, F, 幅, 气声, 声源, 噪带, 送气, 噪形=0,
            鼻增益=0.0, 鼻极=0.0, 鼻零=0.0):
        super()._加(f0, F, 幅, 气声, 声源, 噪带, 送气, 噪形)
        self.帧["鼻增益"].append(float(鼻增益))
        self.帧["鼻极"].append(float(鼻极))
        self.帧["鼻零"].append(float(鼻零))

    def _声母(self, s: dict, 目标首: np.ndarray, f0起: float):
        """按发音方式生成辅音帧（v8：爆破更短更冲；CV 终点更贴 locus）。"""
        声 = s["声"]
        if not 声:
            return None
        info = 声母_v8.get(声)
        if info is None:
            return None
        方式 = info["方式"]
        缩 = self._缩辅()
        电平 = float(参数["辅音电平倍"])
        增益 = self.辅音增益 * 电平
        轨 = np.asarray(info["轨迹"], dtype=np.float64)
        目 = np.asarray(目标首, dtype=np.float64)
        终点 = 轨 + (目 - 轨) * float(参数["终点混合"])

        if 方式 == "塞":
            self._静音(info["塞闭"] * 缩)
            self._噪声过渡(float(参数["爆破秒"]), info["爆破幅"] * float(参数["爆幅倍"]) * 增益,
                           0, info["爆破带"], 轨, 轨, 送气=0.8 if info["送气"] else 0.3)
            if info["送气"]:
                self._噪声过渡(info["VOT"] * 缩 * float(参数["VOT倍"]),
                               float(参数["送气电平"]) * 增益, 1, None, 轨, 终点, 送气=1.0)
            else:
                self._噪声过渡(max(info["VOT"] * 缩 * float(参数["VOT倍"]), 0.012),
                               float(参数["不送气电平"]) * 增益, 1, None, 轨, 终点, 送气=1.0)
            return 终点

        if 方式 == "擦":
            self._噪声过渡(info["时长"] * 缩, info["幅"] * 增益,
                           info.get("噪形", 0), info["频带"], 轨, 终点, 送气=1.0)
            return 终点

        if 方式 == "塞擦":
            self._静音(info["塞闭"] * 缩)
            self._噪声过渡(float(参数["塞擦爆破秒"]),
                           info["爆破幅"] * float(参数["爆幅倍"]) * 增益,
                           0, info["爆破带"], 轨, 轨, 送气=0.8)
            self._噪声过渡(info["擦时"] * 缩 * float(参数["塞擦擦时倍"]),
                           info["幅"] * 增益, 0, info["频带"], 轨, 终点, 送气=1.0)
            return 终点

        # ★ 浊声母（鼻/边/近音）**时长缩放沿用 缩（v7 口径）**：
        #   缩底=1.0 会把鼻音段拉长到 60ms，使 v7 的 B3（浊声母电平窗 40ms）与 C3（三段F0 取样）
        #   这两条**保号保定义**边界臂落到窗外（实测见 01_预检报告.md）；故此处不随 缩底。
        self._浊段(info["时长"] * self.缩, f0起, 轨, 终点,
                   self.幅度 * info["幅"] * self.辅音增益 * H7.浊声母增益.get(声, 1.66),
                   送气=info.get("送气", 0.03))
        return 终点

    def _元音(self, s: dict, j: int, n: int, 标点: str, 时长倍: float,
              重音: bool, 微颤相: float, 首加成: float, 末尾: bool, 起始F):
        """与 韵律_v7._元音 同，唯 `过渡帧` 由 30ms → 参数[过渡秒]（45ms）。"""
        韵 = s["韵"]
        目s = [np.array([t[0] * self.s[0], t[1] * self.s[1], t[2] * self.s[2]])
              for t in s["目标s"]]
        f4, f5 = H7._高共振峰(韵)
        f4 *= self.s4
        f5 *= self.s5
        关键 = H7._关键点(韵, len(目s))
        时长 = 0.200 * self.缩 * 时长倍 * (
            1.0 + float(参数["复合韵时长倍"]) * max(len(目s) - 1, 0))
        帧数 = max(int(round(时长 * _帧率)), 3)
        过渡帧 = max(1, int(round(float(参数["过渡秒"]) * _帧率)))
        尾 = s["尾"]
        鼻 = (np.asarray(H7.鼻尾目标[尾], dtype=np.float64) *
             np.array([self.s[0], self.s[1], self.s[2]])) if 尾 else None
        # ★ 鼻尾全音节化：v7/v8 只在短语末音节生成鼻尾，导致句中 -n/-ng 丢失
        #   （多句 ASR 实测「鼻尾·句中」错误率 0.839）；此处对**每个**带 -n/-ng 韵尾的音节都生成。
        # ★ 借帧不拉长语速：从元音段借 N尾 帧给鼻尾（帧数 = 帧数 − N尾，下限 6），
        #   整句时长基本不变；`时长` 仍只用于 `_f0(...)`，语义不变。
        N尾 = int(参数["鼻尾帧数"]) if 末尾 else int(参数["鼻尾帧数句中"])
        A尾 = float(参数["鼻尾幅"]) if 末尾 else float(参数["鼻尾幅句中"])
        if 鼻 is not None:
            帧数 = max(帧数 - N尾, 6)

        for f in range(帧数):
            t = f / max(帧数 - 1, 1)
            目 = H7._插目标(目s, t, 关键)
            if 起始F is not None and f < 过渡帧:
                w = H7._平滑步((f + 1) / 过渡帧)
                目 = np.asarray(起始F) * (1.0 - w) + 目 * w
            if 鼻 is not None and t > 0.70:
                w = H7._平滑步((t - 0.70) / 0.30)
                目 = 目 * (1.0 - w) + 鼻 * w
            包 = 1.0
            if f < 2:
                包 *= (f + 1) / 2.0
            if f >= 帧数 - 2:
                包 *= max(0.55, 1.0 - 0.22 * (f - (帧数 - 3)))
            幅 = self.幅度 * 包 * (1.06 if 重音 else 1.0) * float(self.rng.uniform(0.97, 1.03))
            if s["调"] == 5:
                幅 *= 0.85
            f0 = self._f0(s["调"], t, j, n, 标点, 重音, 首加成, 微颤相, 时长)
            self._加(f0, (目[0], 目[1], 目[2], f4, f5), 幅, self.气声, 1, None, 0.0)

        if 鼻 is not None:
            # ★ 持续包络：原陡降包络（前 2 帧有量、后 4 帧近无声）会让鼻尾听不出来；
            #   改为自 ~0.92·A尾 缓降至 ~0.70·A尾 的持续型，F0 仍每帧轻微下降。
            f0l = self._f0(s["调"], 1.0, j, n, 标点, False, 首加成, 微颤相, 时长)
            for k in range(N尾):
                w = (k + 1.0) / N尾
                包 = A尾 * (0.92 - 0.22 * w)
                self._加(f0l * (1.0 - 0.008 * k),
                         (鼻[0], 鼻[1], 鼻[2], f4, f5),
                         self.幅度 * 包, min(self.气声 + 0.02, 0.8), 1, None, 0.0,
                         鼻增益=float(参数["鼻增益"]),
                         鼻极=float(参数["鼻极Hz"]),
                         鼻零=float(参数["鼻零Hz"]))


