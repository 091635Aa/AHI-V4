    不送气电平=0.32,     # 不送气塞 VOT 噪声电平
    复合韵时长倍=0.0,    # 每个额外韵母目标追加的时长比例（实测 0.20 反而变差 ⇒ 默认 0，仅留作搜索维）
    鼻增益=0.0,          # 鼻尾并联支路增益（0=关闭；>0 时用 鼻极/鼻零 造真鼻音共鸣）
    鼻极Hz=250.0,        # 鼻极（低频鼻共鸣）
