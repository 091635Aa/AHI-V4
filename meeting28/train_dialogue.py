"""meeting28/train_dialogue.py —— #220 专门培训 + v2 五判据实测。

流程：语料 3 epoch 培训（逐 epoch 用 5 个 held-out 改述问题评测检索/作答）→
对话演示（自指×3/记忆问题/组合生成/未知诚实/状态依赖双问）→ 持久化复查 → 判据汇总。
"""
from __future__ import annotations

import io
import os
import sys

ROOT = r"<workspace>/03_AHI\AHI2.1"
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "meeting28"))

from dialogue_v2 import 对话桥v2

_out = io.StringIO()


def 说(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    _out.write(s + "\n")


语料 = ("我最喜欢的颜色是蓝色。\n我养了一只猫叫团子。\n我周末喜欢去爬山。\n"
        "我的工作是程序员。\n我不太喜欢下雨天。")

探针 = [  # 改述族（字符重叠）：(held-out 改述问题, 必含关键词)
    ("我最喜欢什么颜色？", "蓝色"),
    ("我周末喜欢做什么？", "爬山"),
    ("我是做什么工作的？", "程序员"),
    ("我喜欢下雨天吗？", "雨"),
    ("我养的猫叫什么？", "团子"),
]
同义探针 = [  # 同义族（OOV 同义词，字符零重叠）：已知局限，预期如实报未知
    ("我的宠物叫什么名字？", "团子"),
]


def 评测(桥, probes=None):
    """作答正确 = 响应以『这个我记得』开头（真命中）且含关键词。
    （此前假阳性：未知响应含最近段文本也会命中关键词——已修，threshold_calib 教训）"""
    probes = 探针 if probes is None else probes
    正 = 0
    明细 = []
    for q, key in probes:
        r = 桥.步(q)
        ok = r["响应"].startswith("这个我记得") and key in r["响应"]
        正 += int(ok)
        明细.append("%s→%s" % ("√" if ok else "✗", q))
    return 正, 明细


def main():
    说("=" * 72)
    说("#220 对话体 v2：专门培训 + 五判据实测")
    说("=" * 72)

    桥 = 对话桥v2(seed=216)

    # —— 专门培训：逐 epoch 评测（判据⑤ 培训收益） ——
    说("")
    说("【专门培训】5 句事实 × 3 epoch（codec 去重注册，引擎 M 记忆逐轮强化）")
    逐epoch = []          # (作答正确数, 该epoch新异均值)
    ñ线 = []
    for ep in range(3):
        r = 桥.教_v2(语料, epochs=1)
        正, 明细 = 评测(桥)
        ñ线.append(r["新异曲线"][0])
        逐epoch.append(正)
        说("  epoch%d：新异均值 %.4f ｜ 探针作答正确 %d/5（%s）"
           % (ep + 1, r["新异曲线"][0], 正, " ".join(明细)))
    说("  新异曲线（引擎对语料逐轮变熟）：%s" %
       " → ".join("%.4f" % x for x in ñ线))

    # —— 对话演示 ——
    说("")
    说("-" * 72)
    说("【对话演示】")
    for q, tag in [
        ("你是谁？", "自指·身份"),
        ("我今天心情不错。", "陈述→入记忆"),
        ("你现在在想什么？", "自指·当下①"),
        ("我下午要去看牙医。", "陈述→入记忆"),
        ("你现在在想什么？", "自指·当下②（状态已变，响应须不同）"),
        ("你觉得你自己存在吗？", "自指·存在（诚实边界）"),
        ("我最喜欢什么颜色？", "记忆问题（应构成回答）"),
        ("我喜欢什么？", "组合生成（应拼 ≥2 段）"),
        ("番茄炒蛋应该怎么做得好吃？", "全新无关（应如实说没学过）"),
    ]:
        r = 桥.步(q)
        说("你> %s" % q)
        说("AHI> %s" % r["响应"])
        说("")

    r1 = None
    # —— 判据①状态依赖复核：同一问题隔一轮再问 ——
    说("-" * 72)
    说("【判据①复核】同一问题两次：")
    a = 桥.步("你现在在想什么？")["响应"]
    桥.步("我晚上想吃火锅。")
    b = 桥.步("你现在在想什么？")["响应"]
    说("第一次：%s" % a)
    说("第二次：%s" % b)
    状态依赖 = a != b
    说("两次响应不同（真实状态变化兑现）= %s" % 状态依赖)

    # —— 判据③④复核取材 ——
    无关 = 桥.步("股市今天行情怎么样？")["响应"]
    组合 = 桥.步("我喜欢什么？")["响应"]
    未知诚实 = ("没学过" in 无关) or ("不想瞎猜" in 无关)
    组合生成 = 组合.count("『") >= 2

    # —— 持久化复查 ——
    路径 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "v2_chat.pkl")
    桥.保存(路径)
    桥2 = 对话桥v2.载入(路径)
    持久 = "蓝色" in 桥2.步("我最喜欢什么颜色？")["响应"]
    说("")
    说("【持久化】保存/载入后记忆连续 = %s" % 持久)

    # —— 同义族（已知局限）——
    同义正, 同义明细 = 评测(桥, 同义探针)
    说("【同义族（OOV 同义词·已知局限）】作答正确 %d/1（%s）——字符零重叠的『宠物↔猫』"
       "改述低于阈值，如实报未知（同义通向=v3 议题）" % (同义正, " ".join(同义明细)))

    # —— 汇总 ——
    说("")
    说("=" * 72)
    说("【五判据汇总】")
    说("  ①自指响应状态依赖：%s" % ("PASS" if 状态依赖 else "FAIL"))
    说("  ②回答性（改述族培训后 %d/5 ≥ 培训前 %d/5）：%s"
       % (逐epoch[-1], 逐epoch[0], "PASS" if 逐epoch[-1] >= 逐epoch[0] and 逐epoch[-1] >= 4 else "FAIL"))
    说("  ③未知诚实（无关问题不回声）：%s" % ("PASS" if 未知诚实 else "FAIL"))
    说("  ④组合生成（≥2 段拼新句）：%s" % ("PASS" if 组合生成 else "FAIL"))
    说("  ⑤持久化记忆连续：%s" % ("PASS" if 持久 else "FAIL"))
    说("=" * 72)

    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "v2_test.log"), "w", encoding="utf-8") as f:
        f.write(_out.getvalue())
    print("[log] v2_test.log 已保存")


if __name__ == "__main__":
    main()
