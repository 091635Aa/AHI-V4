# -*- coding: utf-8 -*-
"""meeting28/marathon_test.py —— #222 v3 可持续性五判据实测（100 轮马拉松）。

判据：①同义在线学习 ②马拉松作答不退化（前后 50 轮分块）③行为不塌缩+未知诚实
④引擎自主拍 ⑤身份连续（双重存/载）。
"""
from __future__ import annotations

import io
import os
import sys

ROOT = r"<workspace>/03_AHI\AHI2.1"
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "meeting28"))

from dialogue_v3 import 对话桥v3

_out = io.StringIO()


def 说(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    _out.write(s + "\n")


基础语料 = ("我最喜欢的颜色是蓝色。\n我养了一只猫叫团子。\n我周末喜欢去爬山。\n"
            "我的工作是程序员。\n我不太喜欢下雨天。")
无关池 = ["股市今天行情怎么样？", "番茄炒蛋应该怎么做得好吃？", "篮球比赛谁赢了？",
          "飞机票多少钱一张？", "地球到月球有多远？", "明天的会议几点开？"]
同义问 = "我的宠物叫什么名字？"


def main():
    说("=" * 72)
    说("#222 对话体 v3：可持续性五判据实测（100 轮马拉松）")
    说("=" * 72)
    桥 = 对话桥v3(seed=216)

    # —— Phase A：基础培训 + 同义前测 ——
    桥.教_v2(基础语料, epochs=3)
    前 = 桥.步(同义问)["响应"]
    说("\n【同义前测】%s\n  → %s" % (同义问, 前))
    前未知 = 前.startswith("这个我还没")

    # —— Phase B：对话教学句 + 巩固 + 重标定 + 同义后测 ——
    宠猫前 = 桥.codec.字符相似("宠", "猫")
    桥.步("猫就是我的宠物。")
    说("\n【教学】你> 猫就是我的宠物。")
    桥.巩固()
    桥.重标定(无关池, [q for q, _ in [(同义问, None)]])
    后 = 桥.步(同义问)["响应"]
    宠猫后 = 桥.codec.字符相似("宠", "猫")
    说("【同义后测】%s\n  → %s" % (同义问, 后))
    说("  字符『宠↔猫』相似度：精化前 %.3f → 精化后 %.3f" % (宠猫前, 宠猫后))
    同义命中 = ("猫" in 后) and 后.startswith("这个我记得")

    # —— Phase C：100 轮马拉松（25 周期×4 轮） ——
    说("\n【马拉松】100 轮混合对话（陈述/改述问/无关问/自主拍+自指）")
    记录 = []          # (块号, 类别, 正确)
    事实探针 = []      # (问句, 关键词) 用于重标定
    巩固前 = 桥.巩固次数
    for i in range(25):
        事实 = "我最喜欢的书是故事%d。" % i
        问句 = "我最喜欢的书叫什么？"
        关键 = "故事%d" % i
        无关 = 无关池[i % len(无关池)]

        r1 = 桥.步(事实)["响应"]
        记录.append((i // 12, "陈述", "记下了" in r1))

        事实探针.append((问句, 关键))
        r2 = 桥.步(问句)["响应"]
        记录.append((i // 12, "作答", r2.startswith("这个我记得") and 关键 in r2))

        r3 = 桥.步(无关)["响应"]
        记录.append((i // 12, "未知诚实", r3.startswith("这个我还没")))

        桥.自主拍(2)
        r4 = 桥.步("你现在在想什么？")["响应"]
        记录.append((i // 12, "自指", len(r4) > 20))

        if 巩固前 != 桥.巩固次数:                      # 巩固事件后立即重标定（无漂移窗）
            桥.重标定(无关池, [q for q, _ in (事实探针[-5:] + [(同义问, None)])])
            巩固前 = 桥.巩固次数

    def 块计分(块):
        作答 = [ok for b, c, ok in 记录 if b == 块 and c == "作答"]
        未知 = [ok for b, c, ok in 记录 if b == 块 and c == "未知诚实"]
        自指 = [ok for b, c, ok in 记录 if b == 块 and c == "自指"]
        return (sum(作答) / max(len(作答), 1), sum(未知) / max(len(未知), 1),
                sum(自指) / max(len(自指), 1))

    前50 = 块计分(0)
    后50 = 块计分(1)
    说("  前 50 轮：作答率 %.2f ｜ 未知诚实率 %.2f ｜ 自指有效 %.2f" % 前50)
    说("  后 50 轮：作答率 %.2f ｜ 未知诚实率 %.2f ｜ 自指有效 %.2f" % 后50)
    desc, H = 桥.行为分布()
    说("  记忆段数=%d 巩固次数=%d 行为分布 %s（熵 %.2f bit）"
       % (len(桥.codec._段), 桥.巩固次数, desc, H))

    # —— Phase D：自主性 ——
    桥.自主拍(10)
    身份 = 桥.步("你是谁？")["响应"]
    自主ok = 桥.自主拍数 > 0 and ("第 %d 拍" % 桥.拍) in 身份
    说("\n【自主性】累计自主拍=%d（无用户输入时引擎自发步进）｜身份自报告含当拍数=%s"
       % (桥.自主拍数, "第 %d 拍" % 桥.拍 in 身份))

    # —— Phase E：身份连续（双重存/载；链式同点比较——桥B 与 桥A 第二次提问处于同一状态 S1） ——
    路径 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "v3_chat.pkl")
    桥.保存(路径)
    桥A = 对话桥v3.载入(路径)
    桥A.步("你是谁？")                     # S0→S1（该轮入桥A 历史）
    桥A.保存(路径)
    桥B = 对话桥v3.载入(路径)              # 重放至 S1
    身份A = 桥A.步("你是谁？")["响应"]     # 桥A@S1
    身份B = 桥B.步("你是谁？")["响应"]     # 桥B@S1（同一状态点）
    同义B = 桥B.步(同义问)["响应"]
    身份一致 = 身份A == 身份B
    记忆不减 = len(桥B.codec._段) >= len(桥.codec._段)
    同义保持 = ("猫" in 同义B) and 同义B.startswith("这个我记得")
    说("【身份连续】双重存/载后身份自报告一致=%s ｜ 记忆单调不减=%s（%d 段）"
       "｜ 同义命中保持=%s" % (身份一致, 记忆不减, len(桥B.codec._段), 同义保持))

    # —— 汇总 ——
    说("")
    说("=" * 72)
    说("【五判据汇总】")
    说("  ①同义在线学习（前测%s→后测命中）：%s"
       % ("如实未知" if 前未知 else "异常", "PASS" if 同义命中 else "FAIL"))
    说("  ②马拉松作答不退化（后 %.2f ≥ 前 %.2f）：%s"
       % (后50[0], 前50[0], "PASS" if 后50[0] >= 前50[0] and 后50[0] >= 0.8 else "FAIL"))
    说("  ③行为不塌缩+未知诚实（熵 %.2f bit>0.5；后段诚实率 %.2f=1.0）：%s"
       % (H, 后50[1], "PASS" if H > 0.5 and 后50[1] == 1.0 else "FAIL"))
    说("  ④引擎自主拍（%d 拍，身份报告同步）：%s" % (桥.自主拍数, "PASS" if 自主ok else "FAIL"))
    说("  ⑤身份连续（一致/不减/同义保持）：%s"
       % ("PASS" if 身份一致 and 记忆不减 and 同义保持 else "FAIL"))
    说("=" * 72)

    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "marathon_test.log"), "w", encoding="utf-8") as f:
        f.write(_out.getvalue())
    print("[log] marathon_test.log 已保存")


if __name__ == "__main__":
    main()
