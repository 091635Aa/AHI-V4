# 零声母 y/w 归一（pypinyin TONE3 实测输出）
_Y映射 = {"yi": "i", "ya": "ia", "yao": "iao", "ye": "ie", "you": "iou",
          "yan": "ian", "yin": "in", "yang": "iang", "ying": "ing", "yong": "iong",
          "yu": "v", "yue": "ve", "yuan": "van", "yun": "vn"}
_W映射 = {"wu": "u", "wa": "ua", "wo": "uo", "wai": "uai", "wei": "uei",
          "wan": "uan", "wen": "uen", "wang": "uang", "weng": "ueng"}


def 折线(轮廓, t: float) -> float:
    for i in range(len(轮廓) - 1):
        t0, v0 = 轮廓[i]
        t1, v1 = 轮廓[i + 1]
        if t <= t1 or i == len(轮廓) - 2:
            w = 0.0 if t1 <= t0 else min(max((t - t0) / (t1 - t0), 0.0), 1.0)
            return v0 + w * (v1 - v0)
    return 轮廓[-1][1]


def 音高轮廓(调: int, t: float) -> float:
    return 折线(声调表.get(int(调), 声调表[1]), float(t))


def _归一(拼: str):
    """'yuan2' → ('', 'van', 2)；'wo3' → ('', 'uo', 3)；'shi4' → ('sh', 'iii', 4)。"""
    p = str(拼).strip().lower()
    调 = 5
    if p and p[-1].isdigit():
        调 = int(p[-1])
        p = p[:-1]
    # y/w 零声母
    if p.startswith("y"):
        p = _Y映射.get(p, "i" + p[1:])
    elif p.startswith("w"):
        p = _W映射.get(p, "u" + p[1:])
    # 声母
    声 = ""
    for s in 声母序:
        if p.startswith(s):
            声, p = s, p[len(s):]
            break
    # 韵母别名/拼写规则
    if 声 in ("j", "q", "x"):
        if p.startswith("u"):
            p = "v" + p[1:]
    if p in ("iu",):
        p = "iou"
    elif p in ("ui",):
        p = "uei"
    elif p == "un":
        p = "vn" if 声 in ("j", "q", "x") else "uen"
    elif p == "ue":
        p = "ve"
    elif p == "o" and 声 in ("b", "p", "m", "f"):
        p = "uo"
    elif p in ("n", "ng"):
        p = "en"
    elif p == "iu":
        p = "iou"
    # 舌尖元音
    if p == "i":
        if 声 in ("z", "c", "s"):
            p = "ii"
        elif 声 in ("zh", "ch", "sh", "r"):
            p = "iii"
    return 声, p, 调


def 韵母目标(韵: str):
    """韵母 → (目标序列, 韵尾)。未收录时按介音/元音字符兜底（并保持可解释）。"""
    韵 = str(韵)
    if 韵 in 韵母表:
        return 韵母表[韵]
    if len(韵) >= 2 and 韵[0] in ("i", "u", "v"):
        主体 = 韵[1:]
        if 主体 in 韵母表:
            目标s, 尾 = 韵母表[主体]
            return ([单韵母[韵[0]]] + list(目标s), 尾)
    目标s = [单韵母[c] for c in 韵 if c in 单韵母] or [单韵母["e"]]
    尾 = "ng" if 韵.endswith("ng") else ("n" if 韵.endswith("n") else None)
    return (目标s, 尾)


def 解析音节(拼音: str) -> dict:
    声, 韵, 调 = _归一(拼音)
    目标s, 尾 = 韵母目标(韵)
    信息 = 声母.get(声) if 声 else None
    return dict(拼音=str(拼音), 声=声, 韵=韵, 调=调,
                目标s=[tuple(t) for t in 目标s], 尾=尾,
                方式=(信息 or {}).get("方式"),
                轨迹=(信息 or {}).get("轨迹"),
                命中=bool(声 in 声母 if 声 else 韵 in 韵母表))


def 音节列表(文本: str) -> list:
    from pypinyin import lazy_pinyin, Style
    拼s = lazy_pinyin(str(文本), style=Style.TONE3, neutral_tone_with_five=True,
                      errors=lambda x: [c for c in x if c.isalnum()])
    return [解析音节(p) for p in 拼s if p and p[0].isascii()]


def 审计(文本s) -> dict:
    """音韵结构审计（供判据用）：未归一 y/w、未命中韵母、单目标复合韵、舌尖元音。"""
    问题 = []
    总 = 0
    for 文 in 文本s:
        for s in 音节列表(文):
            总 += 1
            q = []
            if not s["命中"]:
                q.append("查表未命中")
            if s["韵"] not in 韵母表:
                q.append("韵母表未收录")
            if len(s["目标s"]) == 1 and s["韵"] in ("ai", "ei", "ao", "ou", "ia", "ie",
                                                   "iao", "iou", "ua", "uo", "uai",
                                                   "uei", "ve", "ian", "van", "iong"):
                q.append("复合韵缺滑移目标")
            if q:
                问题.append(dict(拼音=s["拼音"], 韵=s["韵"], 问题=q))
    return dict(音节数=总, 问题数=len(问题), 问题=问题)


