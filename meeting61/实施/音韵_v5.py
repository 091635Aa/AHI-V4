"""meeting61/实施/音韵_v5.py —— 普通话音韵层（v5 重建，纯规则、无模型）。

v4 的根因（诊断_发音_v5.py 实测，121 音节中 76 个结构性问题）：
  · pypinyin 的 y/w 零声母（我 wo / 愿 yuan / 一 yi / 要 yao …）没有归一，
    y/w 不在声母表 ⇒ 韵母以 y/w 开头 ⇒ 查表失败，退化成「a→o」「u→a」；
  · zhi/chi/shi/ri/zi/ci/si 的舌尖元音 [ʅ]/[ɿ] 被当成 [i]（F2 2200）；
  · ia/ie/iao/iu/ua/uo/uai/ui/ve/ian/üan/iong 等复合韵只给单目标或丢介音；
  · 塞音/擦音没有「部位轨迹（locus）」，CV 过渡无从生成。

本模块只做「字 → 声母/韵母/调 → 共振峰目标序列 + 辅音发音方式」，
不做 DSP（DSP 在 引擎_v5.py），不依赖任何外部模型（C10）。

主要 API
--------
``解析音节(拼音) -> dict``       # 'yuan2' → 声='', 韵='van', 调=2, 目标s=[y, ɛ], 尾='n'
``音节列表(文本) -> [dict]``      # 文本 → 音节 dict 列表
``韵母目标(韵) -> (目标s, 尾)``
``声母参数(声) -> dict | None``
``音高轮廓(调, t) -> 五度值``
"""
