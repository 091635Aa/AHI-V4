# ══════════ M4 多巴胺：大变=+1；目标达成=+4；说出「找到了」；同色偏好 ══════════
def m4_多巴胺():
    from 共存态 import 共存态
    态 = 共存态()
    脑 = 脑器(态, 允许双=True, 允许回报=True)
    脑._安全探 = 沙盒安全源()
    前 = [dict(句柄="B", 框=(400, 400, 100, 100), 心=(450, 450), 主色=(205, 170, 80))]
    后 = [dict(句柄="B", 框=(400, 400, 260, 200), 心=(530, 500), 主色=(205, 170, 80))]
    脑._待归因 = dict(句柄="B", 键="双", 前签=_句柄签名(前), 前元素s=前, t=time.time())
    态.写动作(动作计数=int(态.取动作().get("动作计数", 0)) + 1)
    态.写视觉(后, 帧号=2, 屏幕=(1920, 1080))
    态.写目标(主色=(208, 176, 84), 心=(450, 450), 来源="判据")
    基准 = int(态.取表达()["队列"])
    脑.一拍()
    判("M4-a 大变+目标达成 → 多巴胺大分泌", 脑.多巴胺总 >= 4.0, 脑.多巴胺总, "≥4.0")
    判("M4-b 达成计数", 脑.达成数 == 1, 脑.达成数, "=1")
    弹s = []
    while int(态.取表达()["队列"]) > 0:
        弹s.append(态.取下一句())
    判("M4-c 说了「找到了」（表达队列出队）",
       len(弹s) > 基准 and any("找到" in str(s[1]) for s in 弹s if s),
       "出队=%d 含找到=%s" % (len(弹s), any("找到" in str(s[1]) for s in 弹s if s)), "是")
    记 = 脑.回报.get((205 // 64, 170 // 64, 80 // 64))
    判("M4-d 回报账本按主色桶入账", 记 is not None and 记[0] >= 4.0,
       "桶=%s" % (记,), "≥4.0")
    # 同色偏好：注意打分上 同色元素 +0.5×均值 ≥ +2.0（压过 1.0 新异）
    视 = dict(元素s=[dict(句柄="X", 框=(100, 100, 90, 90), 心=(145, 145), 主色=(10, 10, 10)),
                     dict(句柄="Y", 框=(700, 300, 90, 90), 心=(745, 345), 主色=(200, 160, 70))],
              屏幕=(1920, 1080))
    态.写目标(清=True)                                 # 清目标：纯靠回报偏置（自生目的）
    判("M4-e 无目标下同色偏好（留存）", 脑._注意(视).get("句柄") == "Y", "Y", "Y")


