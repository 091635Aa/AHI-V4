# ══════════ M1 双击物理：手 双击 intent → 沙盒图标打开 ══════════
def m1_双击():
    from 共存态 import 共存态
    from 器官_手 import 手器
    沙 = 沙盒世界()
    态 = 共存态()
    手 = 手器(态, 演练=True, 世界=沙.应用)
    i0 = 沙.图标s[0]["框"]
    心 = (i0[0] + 60, i0[1] + 60)
    手.投喂意图(dict(目标点=心, 键="双", 来源="判据"))
    线 = threading.Thread(target=手.运行, args=(threading.Event(),), daemon=True)
    线.start()
    t0 = time.time()
    while time.time() - t0 < 15 and len(沙.窗口s) == 0:
        time.sleep(0.2)
    判("M1-a 双击→图标运行（开窗）", len(沙.窗口s) == 1, "窗口=%d" % len(沙.窗口s), "=1")
    判("M1-b 双击计数", 沙.统计()["双击"] >= 1, 沙.统计()["双击"], "≥1")
    # 空处双击 = 无事发生（物理诚实）
    n0 = len(沙.窗口s)
    手.投喂意图(dict(目标点=(960, 860), 键="双", 来源="判据"))
    time.sleep(3.0)
    判("M1-c 空处双击=无感", len(沙.窗口s) == n0, "窗口=%d" % len(沙.窗口s), "不变")


# ══════════ M2 到达停顿：到了先停一下再点（≥0.2s） ══════════
def m2_停顿():
    from 共存态 import 共存态
    from 器官_手 import 手器
    沙 = 沙盒世界()
    态 = 共存态()
    手 = 手器(态, 演练=True, 世界=沙.应用)
    心 = (100, 900)                                   # 远处空点（左键点击即可）
    手.投喂意图(dict(目标点=心, 键="左", 来源="判据"))
    计0 = int(态.取动作().get("动作计数", 0))
    t到 = None
    t点 = None
    停 = threading.Event()
    线 = threading.Thread(target=手.运行, args=(停,), daemon=True)
    线.start()
    t0 = time.time()
    while time.time() - t0 < 15:
        a = 态.取动作()
        光 = a.get("光标")
        # 到达拍的光标不进动作槽（直接进 _到达），故用 40px 窗（一步 ≤35px）探「将近到达」
        if 光 and t到 is None and abs(光[0] - 心[0]) <= 40 and abs(光[1] - 心[1]) <= 40:
            t到 = time.time()
        if int(a.get("动作计数", 0)) > 计0 and t点 is None:
            t点 = time.time()
            break
        time.sleep(0.02)
    停.set()
    间 = (t点 - t到) if (t到 is not None and t点 is not None) else -1
    判("M2 到达→动作间隔（看清了再按）", 0.15 <= 间 <= 1.5, round(间, 3), "0.15~1.5s")


