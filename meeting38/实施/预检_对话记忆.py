def P3_两人共用():
    print("=" * 72)
    print("P3 两人共用记忆池：两账号 → 同一生命 → 分别追问")
    print("=" * 72)
    print("（对话槽 写用户说(文, 谁) 带「发言人」字段——两账号共用同一生命/记忆池）")
    态 = 文本态(种子=310).建(接开放域=False)
    态.回合("我叫阿明，我喜欢打篮球。", 谁="阿明")          # 账号A
    态.回合("我叫小红，我喜欢画画。", 谁="小红")            # 账号B
    print("---- A 后接 B，现在分别以 A/B 身份追问（检索按发言人隔离） ----")
    串扰 = []
    for 谁, q, 该有, 不该有 in (("阿明", "我叫什么？", "阿明", "小红"),
                              ("小红", "我叫什么？", "小红", "阿明"),
                              ("阿明", "我喜欢什么？", "篮球", "画画"),
                              ("小红", "我喜欢什么？", "画画", "篮球")):
        r = 态.回合(q, 谁=谁)
        resp = r["响应"]
        ok = (该有 in resp)
        脏 = (不该有 in resp)
        if 脏 and not ok:
            串扰.append((谁, q))
        print("[%s] %s\n[它] %s   → 对=%s 串扰=%s" % (谁, q, resp[:110], ok, 脏))
    print("→ 串扰数=%d（0 才算隔离通过）" % len(串扰))


