def P1_长对话记忆():
    print("=" * 72)
    print("P1 长对话记忆：首句 → 100 句家常 → 追问（不接开放域，纯测记忆）")
    print("=" * 72)
    态 = 文本态(种子=310).建(接开放域=False)
    首 = "我叫阿栈，我最喜欢吃榴莲。"
    r = 态.回合(首)
    print("[我] %s" % 首)
    print("[它] %s" % r["响应"])
    for i in range(100):
        s = "%s（第%d句）。" % (家常词[i % len(家常词)], i + 1)
        态.回合(s)
    print("---- 已插入 100 句家常，记忆段数=%d ----" % len(态.桥.codec._段))
    问法s = ["我最喜欢吃什么？", "你还记得我最喜欢吃什么吗？", "我喜欢吃什么？",
            "我叫什么？", "你还记得我叫什么吗？"]
    for q in 问法s:
        rr = 态.回合(q)
        ok = ("榴莲" in rr["响应"]) if "吃" in q else ("阿栈" in rr["响应"])
        print("[我] %s" % q)
        print("[它] %s   → 记忆命中=%s" % (rr["响应"][:110], ok))
    return 态


def P2_重启持久化():
    print("=" * 72)
    print("P2 重启持久化：综合体 保存→载入 后追问")
    print("=" * 72)
    路径 = os.path.join(HERE, "_预检_记忆.pkl")
    态 = 文本态(种子=310).建(接开放域=False)
    态.回合("我最喜欢的饮料是乌龙茶。")
    态.回合("我养了一只猫，它叫团子。")
    print("原始：段数=%d" % len(态.桥.codec._段))
    try:
        态.桥.保存(路径)
        print("[保存] OK → %s" % 路径)
    except Exception as ex:
        print("[保存] 失败: %r" % ex)
        return
    try:
        from synthesis import 综合体
        桥2 = 综合体.载入(路径)
        print("[载入] OK 段数=%d" % len(桥2.codec._段))
        for q in ("我最喜欢的饮料是什么？", "我的猫叫什么？"):
            r = 桥2.步(q)
            print("[我] %s\n[它] %s" % (q, r["响应"][:110]))
    except Exception as ex:
        print("[载入] 失败: %r" % ex)
    print("→ 注：文本态.py 已接 保存/载入；综合体.保存 已含 开放域根（P4 验证）。")


