"""维度伸缩.py —— 动态维度伸缩（Phase3）：学得越多，向量空间越大。

所有者（2026-10-06）：「把内部变为可动态伸缩……自动将 1024 维度升到 2048 ……按照思考量
自动求出来……它接触的东西越多、学的东西越多，理论来说它的维度就要越多——不然承载不了这么多
智能……当然这个系数不会很大。先把维度提上去。……不降好像也行（只涨不缩）。」

设计（确定性、无随机、无时间——C13）：
  · 学习量 N = 已注册记忆段数（codec._段）——「学的东西」的直接可审计量（只增不减）。
  · 级数 L = min(⌊N / 每级段数⌋, 级上限)；目标D = min(基准D · 2^L, 上限D)。
  · 单调不缩：N 只增 ⇒ 目标D 只增（所有者：「不降也行」）。
  · 系数温和：每 每级段数 段才跳一级（×2），上限 8×（1024→8192）——「系数不会很大」。

跳级是**离散倍增**（×2），不是每次 +75 的连续增量——理由（如实登记）：
  · 维度只能整段重建（升维=重建编解码器+语义探针+事件重放），频繁微调代价高；
  · ×2 与既有 HDC 容量律一致：#310/M4b 实测位翻检索容量随 D 单调锐化
    （1024 在 p=0.45 位翻下 0.384 → 10240 0.996，见 meeting32/加压容量_判读.md）；
  · 每级段数=256 为**预注册结构先验**（非拟合参数）：256 段 ≈ 一次可观的学习量，
    够撑起翻倍容量的收益，也避免「学两句就翻倍」的抖动。

铁律：C1 禁 Transformer｜C9 禁 OCR｜C10 禁外挂模型当器官｜C13 确定性可复现｜C14 不破既有。
"""
from __future__ import annotations


class 维度伸缩器:
    """确定性维度伸缩策略：目标D = f(学习量)。纯函数，无随机、无时间、无副作用。"""

    # 预注册结构先验（变更=结构事件，非调参）
    基准D = 1024
    上限D = 8192
    每级段数 = 256
    级上限 = 3                        # 1024→2048→4096→8192（2^3=8× 封顶）

    def __init__(self, 基准D: int = None, 上限D: int = None,
                 每级段数: int = None, 级上限: int = None):
        self.基准D = int(基准D) if 基准D else type(self).基准D
        self.上限D = int(上限D) if 上限D else type(self).上限D
        self.每级段数 = max(int(每级段数) if 每级段数 else type(self).每级段数, 1)
        self.级上限 = int(级上限) if 级上限 is not None else type(self).级上限

    def 级数(self, 学习量: int) -> int:
        n = max(int(学习量), 0)
        return min(n // self.每级段数, self.级上限)

    def 目标D(self, 学习量: int) -> int:
        L = self.级数(学习量)
        return int(min(self.基准D * (2 ** L), self.上限D))

    def 需升级(self, 当前D: int, 学习量: int) -> bool:
        return self.目标D(学习量) > int(当前D)

    def 说明(self, 学习量: int) -> dict:
        L = self.级数(学习量)
        return dict(学习量=int(学习量), 级数=L, 目标D=self.目标D(学习量),
                    基准D=self.基准D, 上限D=self.上限D, 每级段数=self.每级段数)