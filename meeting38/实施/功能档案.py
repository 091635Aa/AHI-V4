"""meeting38/实施/功能档案.py —— V3 模块二：操作干净化（执行层重构，纯新增）。

问题（所有者 2026-10-06）：点了 WPS 的「AI模板」之类干扰项，逻辑乱晃；操作傻、人机。
根因：**没有功能档案**——它不知道「这个按钮点了会怎样」，只凭新异度驱动探索。

V3 三层过滤：
  第一层 界面类型识别：进入某界面 → 识别类型（如 WPS→「文档编辑器」）→ 从记忆底图 M 调出操作经验。
  第二层 区域功能档案：每个元素除形状束外，加「功能标签」＝亲历点击后世界怎么变
        （复用 `语义.功能签名`）→ 可用 / 干扰项 / 未知。
  第三层 干净操作律：可用优先点；未知先看（眼跳扫描）不点；干扰项标记回避、不再点。

节奏感：远离目标全速 → 接近减速 → 到达前停 0.2s（看清了再按）→ 按下干脆。

红线：C1（无 Transformer）｜C9（无 OCR，只用元素几何/世界差分）｜C10（无外挂模型）
     ｜C13（确定性：标签规则无随机；同输入同输出）。
"""
from __future__ import annotations

# ── 界面类型规则（关键词→类型；纯字符串匹配，无模型）──
_界面规则 = (
    (("wps", "word", "文档", "writer", "文字"), "文档编辑器"),
    (("excel", "表格", "sheet", "工作簿"), "表格编辑器"),
    (("powerpoint", "ppt", "演示", "幻灯片"), "演示编辑器"),
    (("chrome", "edge", "firefox", "浏览器", "browser", "网页"), "浏览器"),
    (("资源管理器", "explorer", "文件夹", "此电脑"), "文件管理器"),
    (("设置", "settings", "控制面板"), "系统设置"),
    (("终端", "cmd", "powershell", "命令"), "终端"),
)
# 每类界面的「操作经验」（第一层从 M 调出的先验；先验只作提示，不决定动作）
_界面经验 = {
    "文档编辑器": "新建空白文档=可用；新建模板/AI模板=易干扰；保存/另存=可用。",
    "表格编辑器": "单元格/公式=可用；模板市场=易干扰。",
    "演示编辑器": "新建空白演示=可用；模板/AI=易干扰。",
    "浏览器": "地址栏/正文区=可用；广告/推荐位=干扰项；导航区=可点击但先不点。",
    "文件管理器": "文件夹=进入；文件=打开；属性=查看。",
    "系统设置": "谨慎：含删除/卸载/重置一类落点一律回避。",
    "终端": "危险：不主动输入。",
    "通用界面": "无先验，按未知处理（先看不点）。",
}

# 危险落点（安全保守：含这些词的**已知功能标签**直接标回避）
_危险词 = ("删除", "卸载", "格式化", "重置", "清空", "支付", "付款", "转账",
          "注销", "关机", "重启", "关闭")

试看上限 = 2          # 未知元素「先看」的次数上限；看过仍未知 → 允许试探一次（学习入口）


def 元素键(e: dict) -> str:
    """元素的稳定键：优先句柄，否则用框/主色派生（无随机、无 OCR）。"""
    if not isinstance(e, dict):
        return "?"
    句 = e.get("句柄")
    if 句 is not None:
        return str(句)
    框 = e.get("框") or (0, 0, 0, 0)
    色 = e.get("主色") or (0, 0, 0)
    if isinstance(色, (int, float)):
        色 = (int(色), 0, 0)
    return "b%d_%d_%d_%d|c%d_%d_%d" % (int(框[0]), int(框[1]), int(框[2]), int(框[3]),
                                       int(色[0]), int(色[1]), int(色[2]))


class 功能档案:
    """三层过滤 + 节奏感。不 import 任何器官（对七路零侵入）；可与 语义图/记忆桥 可选挂接。"""

    def __init__(self, 种子: int = 3800, 语义图=None, 记忆桥=None):
        self.种子 = int(种子)
        self.语义 = 语义图
        self.记忆 = 记忆桥
        self.界面 = ""                               # 当前界面类型
        self.界面史: dict = {}                       # 类型 → 出现次数
        self.元素: dict = {}                         # 键 → {标签, 看次数, 试次数, 证据[]}
        self.回避: set = set()
        self.统计 = dict(点=0, 看=0, 回避出招=0, 可用点=0, 试探=0)

    # ══════════ 第一层：界面类型识别 ══════════
    def 识界面(self, 标题: str) -> dict:
        t = str(标题 or "").lower()
        类 = "通用界面"
        for 词s, 名 in _界面规则:
            if any(w in t for w in 词s):
                类 = 名
                break
        if 类 != self.界面:
            self.界面 = 类
            self.界面史[类] = self.界面史.get(类, 0) + 1
        经验 = _界面经验.get(类, _界面经验["通用界面"])
        先验 = None
        if self.记忆 is not None:                    # 从 M 调出「该界面操作经验」
            try:
                先验 = self.记忆.查_界面(类)
            except Exception:
                先验 = None
        return dict(类型=类, 经验=经验, 记忆先验=先验, 首次=bool(self.界面史.get(类, 0) == 1))

    # ══════════ 第二层：区域功能档案（功能标签）══════════
    def _档(self, 键: str) -> dict:
        d = self.元素.get(键)
        if d is None:
            d = dict(标签="未知", 看次数=0, 试次数=0, 证据=[])
            self.元素[键] = d
        return d

    def 判(self, e) -> str:
        键 = 元素键(e) if isinstance(e, dict) else str(e)
        return self._档(键)["标签"]

    def 标(self, 键: str, 标签: str, 证据: str = "") -> dict:
        """显式标注（教学/复盘用）。标签 ∈ 可用|干扰项|未知|回避。"""
        d = self._档(键)
        d["标签"] = 标签
        if 证据:
            d["证据"].append(str(证据)[:80])
            d["证据"] = d["证据"][-16:]
        if 标签 in ("干扰项", "回避"):
            self.回避.add(键)
        elif 标签 == "可用" and 键 in self.回避:
            self.回避.discard(键)
        return d

    def 记点击(self, 键: str, 前元素s, 后元素s, 真实命中=None,
              危险词: str = "") -> dict:
        """亲历点击 → 世界差分 → 功能标签。差分口径复用 语义.功能签名（若挂了语义图则同步）。"""
        前 = {元素键(e): e for e in (前元素s or []) if isinstance(e, dict)}
        后 = {元素键(e): e for e in (后元素s or []) if isinstance(e, dict)}
        新增 = [k for k in 后 if k not in 前]
        消失 = [k for k in 前 if k not in 后]
        变化 = [k for k in 前 if k in 后 and str(前[k].get("字", "")) != str(后[k].get("字", ""))]
        if self.语义 is not None:
            try:
                self.语义.记点击(键, 前元素s, 后元素s, 真实命中句柄=真实命中)
            except Exception:
                pass
        # ── 标签规则（确定性；无 OCR、无模型）──
        危 = str(危险词 or "")
        if not 危:
            for k in (新增 + 消失):
                if any(w in str((后.get(k) or 前.get(k) or {}).get("字", "")) for w in _危险词):
                    危 = "危词"
                    break
        if 危:
            标签, 由 = "回避", "落点含危险词（安全保守）"
        elif len(新增) >= 3 and len(消失) == 0:
            标签, 由 = "干扰项", "一点冒出一堆新东西（弹窗/面板）"
        elif len(变化) >= 1 and len(新增) <= 2:
            标签, 由 = "可用", "原处发生实质变化（内容/页面更新）"
        elif len(新增) == 0 and len(消失) == 0 and len(变化) == 0:
            标签, 由 = "未知", "点下去世界无感"
        else:
            标签, 由 = "未知", "差分不足以定性（新增%d/消失%d/变化%d）" % (
                len(新增), len(消失), len(变化))
        d = self._档(键)
        d["试次数"] = int(d.get("试次数", 0)) + 1
        d["标签"] = 标签
        d["证据"].append("点击→%s（%s）" % (标签, 由))
        d["证据"] = d["证据"][-16:]
        if 标签 == "回避":
            self.回避.add(键)
        return dict(键=键, 标签=标签, 由=由,
                    新增=len(新增), 消失=len(消失), 变化=len(变化))

    # ══════════ 第三层：干净操作律 ══════════
    def 挑(self, 焦点, 元素s) -> dict:
        """出招裁决：可用优先点；未知先看不点；干扰/回避不点。返回
        {动作: 点|看|None, 目标: 元素|None, 理由: str}。
        无候选或全回避 ⇒ 动作 None（本拍不出招，交还注意扫描）。"""
        可用, 未知, 避 = [], [], []
        for e in (元素s or []):
            if not isinstance(e, dict):
                continue
            键 = 元素键(e)
            标 = self._档(键)["标签"]
            if 标 == "可用":
                可用.append((键, e))
            elif 标 in ("干扰项", "回避") or 键 in self.回避:
                避.append((键, e))
            else:
                未知.append((键, e))
        if 可用:
            # 可用优先：若焦点本身可用则点焦点，否则点第一个可用（插入序确定 → 确定性）
            键, e = 可用[0]
            for k, x in 可用:
                if 焦点 is not None and 元素键(焦点) == k:
                    键, e = k, x
                    break
            self.统计["可用点"] += 1
            self.统计["点"] += 1
            return dict(动作="点", 目标=e, 理由="功能标签=可用，优先点它")
        if 未知:
            # 未知：先看（眼跳扫描）；看过上限仍未知 → 允许试探一次（学习入口）
            for 键, e in 未知:
                d = self._档(键)
                if int(d.get("看次数", 0)) < 试看上限:
                    d["看次数"] = int(d.get("看次数", 0)) + 1
                    self.统计["看"] += 1
                    return dict(动作="看", 目标=e,
                                理由="功能标签=未知，先看第%d次，不点" % d["看次数"])
            # 都看够了 → 挑一件试探（一次性，试后出标签）
            键, e = 未知[0]
            self._档(键)["试探标记"] = True
            self.统计["试探"] += 1
            self.统计["点"] += 1
            return dict(动作="点", 目标=e, 理由="看够了仍未知，试探一次以便建档")
        if 避:
            self.统计["回避出招"] += 1
            return dict(动作=None, 目标=None,
                        理由="候选全是干扰项/回避项（%d 件），本拍不出招" % len(避))
        return dict(动作=None, 目标=None, 理由="无候选")

    # ══════════ 节奏感 ══════════
    @staticmethod
    def 节奏(距目标: float) -> dict:
        """远离全速 → 接近减速 → 到达前停 0.2s → 按下干脆。返回速度系数与到达停顿。"""
        try:
            d = float(距目标)
        except Exception:
            d = 9999.0
        if d >= 400.0:
            速 = 1.0
        elif d >= 60.0:
            速 = 0.35 + 0.65 * (d / 400.0)              # 线性减速
        else:
            速 = 0.35
        到达停顿 = 0.2 if d <= 20.0 else 0.0
        return dict(速度系数=round(速, 3), 到达停顿s=到达停顿,
                    阶段=("远·全速" if d >= 400 else ("近·减速" if d >= 60 else "到·停顿")))

    # ══════════ 快照（判据/审计）══════════
    def 快照(self) -> dict:
        分 = {"可用": 0, "干扰项": 0, "回避": 0, "未知": 0}
        for d in self.元素.values():
            分[d.get("标签", "未知")] = 分.get(d.get("标签", "未知"), 0) + 1
        return dict(界面=self.界面, 界面史=dict(self.界面史),
                    元素数=len(self.元素), 标签分布=分,
                    回避数=len(self.回避), 统计=dict(self.统计))