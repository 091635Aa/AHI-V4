# ════ N1 形状束：色无关 + 区分度 ════
def n1_形状束():
    沙 = 沙盒世界()
    帧 = 沙.帧()
    from 共存态 import 共存态
    描 = 形状描述子(共存态().编码)

    def 眼裁(帧, 框, m=6):
        H, W = 帧.shape[:2]
        return 帧[max(0, 框[1] - m):min(H, 框[1] + 框[3] + m),
                  max(0, 框[0] - m):min(W, 框[0] + 框[2] + m)]

    束s = [描.形状束(眼裁(帧, ic["框"])) for ic in 沙.图标s]
    异 = max(描.相似(束s[i], 束s[j]) for i in range(4) for j in range(4) if i != j)
    判("N1-a 异图标相似上界", 异 <= 0.70, round(异, 2), "≤0.70")
    # 色不变：icon0 贴到紫底画布（各自独立画布）——平移 / 平移+框抖4px / 缩放0.75
    import cv2
    ic = 沙.图标s[0]["框"]
    原样 = 帧[ic[1]:ic[1] + ic[3], ic[0]:ic[0] + ic[2]]
    变体s = []
    imgA = np.full((300, 300, 3), (120, 30, 160), np.uint8)
    imgA[100:100 + ic[3], 150:150 + ic[2]] = 原样
    变体s.append((imgA, (150, 100, ic[2], ic[3])))       # 平移+换底
    变体s.append((imgA, (154, 104, ic[2], ic[3])))       # 框抖 4px
    imgB = np.full((300, 300, 3), (120, 30, 160), np.uint8)
    缩 = cv2.resize(原样, (90, 90), interpolation=cv2.INTER_AREA)
    imgB[105:195, 105:195] = 缩
    变体s.append((imgB, (105, 105, 90, 90)))             # 缩放 0.75
    best = max(描.相似(束s[0], 描.形状束(眼裁(f, k))) for f, k in 变体s)
    判("N1-b 同图标（换底+平移+缩放+抖动）组内最大", best >= 0.80, round(best, 2), "≥0.80")


