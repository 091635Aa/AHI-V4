# ════ N3 图标簿 + RPE 多巴胺 ════
def n3_簿与rpe():
    from 共存态 import 共存态
    态 = 共存态()
    脑 = 脑器(态, 允许双=True, 允许回报=True)
    脑._安全探 = 沙盒安全源()
    from 形状束 import 形状描述子
    描 = 形状描述子(态.编码)
    沙 = 沙盒世界()
    帧 = 沙.帧()
    ic = 沙.图标s[0]["框"]
    束0 = 描.形状束(帧[max(0, ic[1] - 6):ic[1] + ic[3] + 6,
                       max(0, ic[0] - 6):ic[0] + ic[2] + 6])
    前 = [dict(句柄="E0", 框=ic, 心=(ic[0] + 60, ic[1] + 60), 主色=(208, 176, 84))]
    后 = [dict(句柄="E0", 框=(ic[0], ic[1] - 60, ic[2] + 240, ic[3] + 160),
               心=(ic[0] + 180, ic[1] + 20), 主色=(208, 176, 84))]   # 双击后世界大变（窗口开）
    # 第一次：意外发现（+1）+ 命名达成（+3）→ 簿登记 成功=1
    态.写视场(中央凹束s=[束0], 中央凹心=(ic[0] + 60, ic[1] + 60), 中央凹句柄="E0")
    脑._凹视采样()                                       # 眼看过 E0 → 脑的凹视史有它的形状
    态.写动作(动作计数=1)
    态.写视觉(后, 帧号=1, 屏幕=(1920, 1080))
    态.写目标(名称="WPS", 心=(ic[0] + 60, ic[1] + 60), 来源="教学")
    脑._待归因 = dict(句柄="E0", 键="双", 前签=_句柄签名(前), 前元素s=前, t=time.time())
    脑.一拍()
    判("N3-a 簿登记（形状+名+成功1）", len(脑.簿) == 1 and list(脑.簿.values())[0]["成功"] == 1
       and list(脑.簿.values())[0]["名称"] == "WPS", json.dumps(
           {k: v for k, v in list(脑.簿.values())[0].items() if k != "束"}, default=str),
       "1 条/成功=1/名=WPS")
    判("N3-b 意外发现+达成 多巴胺", 脑.多巴胺总 >= 4.0, 脑.多巴胺总, "≥4.0")
    # 第二次：预期确认（+0.4）+ 达成（+3）→ 成功=2 → 直达资格
    态.写动作(动作计数=2)
    脑._待归因 = dict(句柄="E0", 键="双", 前签=_句柄签名(前), 前元素s=前, t=time.time())
    脑.一拍()
    条 = list(脑.簿.values())[0]
    判("N3-c 成功=2（教两三次就会的资格线）", 条["成功"] == 2, 条["成功"], "=2")
    判("N3-d 预期确认多巴胺（0.4+3）", abs(脑.多巴胺总 - 7.4) < 0.01, round(脑.多巴胺总, 2),
       "≈7.4")


