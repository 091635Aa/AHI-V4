# -*- coding: utf-8 -*-
"""meeting38/实施/输出层.py —— V3 模块一：思考不公布 · 输出层重构（纯新增，不改既有器官）。

问题（所有者 2026-10-06 定调）：2.1 把内部思考直接翻译成文本输出 → "像小模型在接龙"，
内容失真、说话没个性、没自我意识。

V3 要求：
  · 思考核继续内部运行，但**不直接翻译成文字**进输出流；
  · 输出层**只读三样东西**：自我状态 S（当前心境数值）、意图向量（下一步想干什么）、
    记忆底图 M 的检索结果（当前话题与什么历史相关）；
  · 输出层据此生成**一句带个性的话**；
  · 个性 = 自我状态 S 的调制 × 记忆 M 的检索结果 × 私有熵源（私房骰子）的偏置；
  · 结果：同样一句话，今天说和明天说**不一样**；
  · 输出流**禁止**出现「我想到…」「我的内部状态是…」这类元话语。

红线：C1 禁 Transformer（无 attention/softmax/梯度）｜C10 禁外挂模型当器官（无预训练 LM）
     ｜C13 确定性可复现（同 seed＋同输入 ⇒ 逐位一致）——个性来自**确定性私有熵源**，
       不是外部不可复现噪声；同输入必同输出。

本模块**不 import 任何器官**（只吃数据、吐句子），故对七路零侵入（C14）。
"""
from __future__ import annotations

import re

import numpy as np

# ── 元话语过滤（输出流一旦命中即剥除/替换；这是模块一的硬约束）──
_元话语 = (
    "我想到", "我想到的是", "我的内部状态", "我的内部状态是", "内部状态",
    "我的思考", "我思考", "我的脑", "神经元", "向量", "激活", "telemetry", "遥测",
    "特征", "概率分布", "模型", "推理过程", "让我分析", "根据我的分析",
)
_元话语_RE = re.compile("|".join(re.escape(k) for k in _元话语))


def 净化(文本: str) -> str:
    """剥除元话语：命中即删该短语（保留其余自然文本）。确定性、无副作用。"""
    if not 文本:
        return ""
    s = _元话语_RE.sub("", str(文本))
    s = re.sub(r"[\s，。]{2,}", lambda m: m.group(0)[0], s).strip(" ，。、")
    return s


def _取(d, *名s, 缺=None):
    """从 dict 里按多个别名取值（S/意图 兼容 2.1 既有字段名）。"""
    if not isinstance(d, dict):
        return 缺
    for 名 in 名s:
        if 名 in d and d[名] is not None:
            return d[名]
    return 缺


def _档(值, 下, 上) -> float:
    """把值线性折到 [0,1]，越界裁剪。"""
    try:
        v = (float(值) - 下) / (上 - 下)
    except Exception:
        v = 0.5
    return max(0.0, min(1.0, v))


# ══════════ 词库（纯确定性模板＋同义替换池；无任何生成式模型）══════════
# 心境开场：按 效价 V 分三档，每档多选（由私熵挑一个）
_开场 = {
    "高": ("嗯", "哎", "对", "好", "讲真", "有意思", "行"),
    "中": ("嗯", "这样", "嗯——", "行吧", "那", "我看看"),
    "低": ("唔", "唉", "说实话", "怎么说呢", "有点闷", "慢着"),
}
# 唤醒 A 高 → 语气更急/更短促的收尾；低 → 更松
_收尾 = {
    "高": ("，就现在", "，快点", "。", "！", "，别磨蹭"),
    "中": ("。", "，嗯", "，你看", "。"),
    "低": ("，慢慢来", "……", "，不急", "。"),
}
# 意图 → 句式骨架（{开} {体} {尾}）
_骨架 = {
    "说": ("{开}，{体}{尾}",),
    "问": ("{开}，我想问一句——{体}{尾}", "{开}，{体}？", "{开}，{体}，能说说吗{尾}"),
    "沉默": ("……", "{开}，先不说这个{尾}", "这事我搁一下{尾}"),
    "操作": ("{开}，我去弄一下{体}{尾}", "{开}，这个我来动手{尾}", "{开}，先把它点开{体}{尾}"),
}


class 输出层:
    """V3 输出层：只读 (意图向量, S, M检索结果) → 一句带个性的话。不翻译思考核内容。"""

    def __init__(self, 种子: int = 310, 私盐: int = 0):
        self.种子 = int(种子)
        self.私盐 = int(私盐)                       # 私有熵源的盐（对外不可预测；对己确定）

    # ── 私有熵源（私房骰子）：确定性但外部不可预测 ──
    def _私熵(self, S: dict, 意图向量: dict):
        拍 = int(_取(S, "拍", "呼吸拍", "自体拍", 缺=0) or 0)
        拍2 = int(_取(意图向量, "拍", 缺=0) or 0)
        return np.random.default_rng((self.种子, 拍, 拍2, self.私盐, 0x5EED))

    # ── 读 S（自我状态）：兼容 2.1 自我槽/综合体遥测的多种字段名 ──
    @staticmethod
    def 读心境(S: dict) -> dict:
        S = S or {}
        点 = _取(S, "点", "情感点", 缺={}) or {}
        V = float(_取(点, "V", "效价", 缺=_取(S, "V", "效价", 缺=0.0)))
        A = float(_取(点, "A", "唤醒", 缺=_取(S, "A", "唤醒", 缺=0.5)))
        e = _取(S, "e", "能量")
        消化债 = float(_取(S, "消化债", 缺=0.0) or 0.0)
        饱足 = float(_取(S, "饱足", 缺=1.0) or 1.0)
        新异 = float(_取(S, "ñ", "新异", 缺=0.0) or 0.0)
        区 = str(_取(S, "区", "最近区域", 缺="") or "")
        return dict(V=V, A=A, e=e, 消化债=消化债, 饱足=饱足, 新异=新异, 区=区)

    # ── 读意图向量：说 / 问 / 沉默 / 操作 ──
    @staticmethod
    def 读意图(意图向量: dict) -> dict:
        d = 意图向量 or {}
        类 = _取(d, "类别", "动作", "类", 缺=None)
        if 类 is None:
            键 = _取(d, "键", 缺=None)
            if 键 in ("左", "右", "双", "中", "滚") or _取(d, "滚动", 缺=None) is not None \
                    or _取(d, "键入", 缺=None) is not None or _取(d, "拖到", 缺=None) is not None:
                类 = "操作"
            elif _取(d, "问", 缺=False):
                类 = "问"
            else:
                类 = "说"
        类 = str(类)
        if 类 not in _骨架:
            类 = "说"
        目标 = _取(d, "目标点", "句柄", "名称", "目标", 缺="")
        return dict(类别=类, 目标=目标, 强度=float(_取(d, "强度", 缺=1.0) or 1.0))

    # ── 读 M 检索结果：[(段, 分), ...] 或 dict ──
    @staticmethod
    def 读记忆(M检索结果) -> dict:
        命中 = None
        分 = 0.0
        if isinstance(M检索结果, dict):
            命中 = _取(M检索结果, "段", "文本", "top1", 缺=None)
            分 = float(_取(M检索结果, "分", "相似", 缺=0.0) or 0.0)
        elif isinstance(M检索结果, (list, tuple)) and M检索结果:
            首 = M检索结果[0]
            if isinstance(首, (list, tuple)) and len(首) >= 2:
                命中, 分 = str(首[0]), float(首[1])
            else:
                命中 = str(首)
        # ★截断修复：网页正文含换行/多段，整段塞进引号会毁掉句子结构。
        #   取**首个有意义的行/句**，按标点收尾，再限长（保留语义，不再出现裸换行）。
        return dict(命中=_摘要一句(命中), 分=float(分))

    # ── 读内态（五内核的当下状态）：把「它脑子里正在发生什么」折成可表达的倾向 ──
    @staticmethod
    def 读内态(内态) -> dict:
        """从 `内核宿主.内核态()` 的产出里读出可表达的内态（缺项=中性，不编造）。

        · ε_self 相对自身慢基线的**异常**（自模型预测不了自己）→ 想停下想/反刍；
        · 自指束一致度 → 「我此刻还像不像我」（对身份锚的余弦）；
        · 思核换站倾向 → 念头在不在流动（非周期 itinerancy）；
        · 顿悟条数 → 是否刚发生过相变。
        这里**只读不判**：不做阈值裁决，只把「高于平时」的程度折成 0~1 的倾向值。
        """
        d = 内态 or {}
        if not d.get("挂载"):
            return dict(有=False)
        zm = d.get("自模型") or {}
        drv = d.get("真学习") or {}
        zk = d.get("自我回路") or {}
        sx = d.get("思核") or {}
        dw = d.get("顿悟涌现") or {}
        ε = zm.get("ε最近")
        慢 = drv.get("ε慢基线")
        异 = None
        if ε is not None and 慢 is not None:
            异 = max(0.0, float(ε) - float(慢))          # 相对自身基线的异常量（自归一）
        return dict(有=True, ε=ε, ε慢=慢, 异常=异,
                    一致度=zk.get("最近一致度"), 自我迹=zk.get("迹条数"),
                    思核迹=sx.get("迹条数"), 顿悟=dw.get("顿悟条数") or 0)

    # ══════════ 生成正文（模块一对外的唯一入口）══════════
    def 生成正文(self, 意图向量: dict, S: dict, M检索结果=None, 内态=None) -> str:
        """只读 → 一句带个性的话。

        个性 = S 调制（心境档）× M 检索结果（话题） × 私熵偏置（同义挑选/语气）
              × **内态倾向**（五内核：ε_self 异常 / 自指束一致度 / 念头流动 / 顿悟）。
        同输入 ⇒ 同输出（C13）；S / M / 内态 变 ⇒ 输出变（"今天说和明天说不一样"）。
        """
        心 = self.读心境(S)
        意 = self.读意图(意图向量)
        记 = self.读记忆(M检索结果)
        态 = self.读内态(内态)
        rng = self._私熵(S, 意图向量)

        # ① S 调制：心境三档
        V档 = "高" if 心["V"] > 0.15 else ("低" if 心["V"] < -0.15 else "中")
        A档 = "高" if 心["A"] > 0.6 else ("低" if 心["A"] < 0.4 else "中")
        开 = _开场[V档][int(rng.integers(len(_开场[V档])))]
        尾 = _收尾[A档][int(rng.integers(len(_收尾[A档])))]

        # ② M 检索结果 → 话题主体（命中优先，否则按心境/意图兜底）
        #    ★措辞：M 里存的可能是**它自己看来的**网页正文（不是对方说的）——
        #    所以按来源区分「你先前说过」/「我自己看来的」，不再一律说"你说过"。
        if 记["命中"] and 记["分"] >= 0.2:
            源 = str(_取(M检索结果, "来源", 缺="") or "") if isinstance(M检索结果, dict) else ""
            引 = ("我自己看来的" if 源 in ("网页", "复盘", "自我线程", "网页正文")
                  else "你先前说过")
            体 = "%s『%s』，这事我还记得" % (引, 记["命中"])
        elif 意["类别"] == "问":
            体 = "我手头这事你怎么看"
        elif 意["类别"] == "操作":
            体 = "（%s）" % (_挡目标(意["目标"]))
        else:
            体 = _按心境兜底(心, rng)

        # ③ 内态倾向 → 追加半句**真内态**（由五内核实况决定；中性时不追加，不无病呻吟）
        内 = _内态半句(态, rng)

        # ④ 骨架选择（私熵挑一个同义骨架）
        骨s = _骨架[意["类别"]]
        骨 = 骨s[int(rng.integers(len(骨s)))]
        句 = 骨.format(开=开, 体=体, 尾=尾)
        return 净化(_并句(句, 内))


def _摘要一句(文本, 上限: int = 44) -> str:
    """把一段记忆文本压成**一句可直接引用的话**：按句末标点断开，去空白与零宽。"""
    if not 文本:
        return None
    t = str(文本)
    for ch in ("\u200b", "\u200c", "\u200d", "\ufeff"):
        t = t.replace(ch, "")
    t = t.replace("\r", "\n")
    行s = [x.strip() for x in t.split("\n") if x.strip()]
    if not 行s:
        return None
    首 = 行s[0]
    for 标 in ("。", "！", "？", ".", "!", "?", "；", ";"):
        i = 首.find(标)
        if 0 <= i < 上限:
            首 = 首[: i + 1]
            break
    return 首[:上限]


def _挡目标(目标) -> str:
    """把意图里的目标点/句柄转成**不泄露内部结构**的短描述。"""
    if 目标 is None or 目标 == "":
        return "眼前这件"
    if isinstance(目标, (list, tuple, np.ndarray)) and len(目标) >= 2:
        return "屏幕上一件东西"
    s = str(目标)
    return s[:12] if s and not s.isdigit() else "眼前这件"


def _按心境兜底(心: dict, rng) -> str:
    """无记忆命中时的兜底主体——仍由心境决定，保证个性可见。"""
    if 心["消化债"] > 0.1:
        池 = ("心里攒着点没想透的，正慢慢捋", "有些东西还没消化完，先搁着",
              "我心里还压着几件没理顺的事")
    elif 心["新异"] > 0.6:
        池 = ("眼前冒出来些新东西，我盯着看", "刚碰见点没见过的，挺新鲜",
              "有新东西进来了，我留意着呢")
    elif 心["区"] and 心["区"] not in ("", "—"):
        池 = ("我现在心里偏%s" % 心["区"], "这会儿我这心思像是%s" % 心["区"],
              "说不上为什么，人有点%s" % 心["区"])
    else:
        池 = ("就这么待着，挺好", "没什么特别的，我在这", "我在，随便聊聊")
    return 池[int(rng.integers(len(池)))]


# ══════════ 内态外化（五内核 → 半句话）══════════
# 语义说明（为什么这么写）：这些都是**第一人称的自我感受**，不是元话语——
# 「我有点拿不准自己」= ε_self 高于自身慢基线；「我还是我」= 自指束对身份锚一致度高。
# 它们**读真值**（内核态），不是骰子编的；但用词仍是私熵在池里挑（保留个性）。
_半句_失配 = ("我有点拿不准自己现在是什么状态", "我刚才没料到自己会这样",
             "我对自己下一步有点没底", "这回我没算准自己")
_半句_熟悉 = ("我知道自己现在是什么样", "这会儿我心里是清楚的", "我稳得住")
_半句_流动 = ("一个念头接一个念头往外冒", "脑子里还在转，停不太下来",
             "想法有点自己往前跑", "我还在往下想")
_半句_固化 = ("想的事收拢到一处了", "念头慢慢定下来了", "我大致定下方向了")
_半句_顿悟 = ("刚才那一下，我像是想通了点什么", "有个东西忽然通了",
             "前面卡着的地方松开了", "我像是跨过了一道坎")


def _内态半句(态: dict, rng) -> str:
    """把内态倾向折成**一个**半句追加（最多一个，避免堆砌）。

    取用优先级（先强后弱，均可缺席 ⇒ 返回空串）：
      ① 顿悟条数 > 0 且相对上一拍新增 → 相变刚发生（最强，优先说）；
      ② ε 异常（ε_self 明显高于自身慢基线）→ 失配/没底；
      ③ 自指束一致度高 → 「我还是我」；低 → 略去（不自夸也不自贬，避免编造）。
    其余（念头流动/固化）作语气补充，不单独成句。

    ★标点：返回的片段**自带前导标点**，且调用方会剥掉原句尾的重复标点——
    首版实测出「…这事我还记得！。这回我没算准自己」这种双标点（审计遗留观感缺陷）。
    """
    if not (态 or {}).get("有"):
        return ""
    if int(态.get("顿悟") or 0) > 0:
        return "。" + _半句_顿悟[int(rng.integers(len(_半句_顿悟)))]
    异 = 态.get("异常")
    if 异 is not None and 异 > 0.15:
        return "。" + _半句_失配[int(rng.integers(len(_半句_失配)))]
    致 = 态.get("一致度")
    if 致 is not None and 致 > 0.02:
        return "，" + _半句_熟悉[int(rng.integers(len(_半句_熟悉)))]
    if int(态.get("思核迹") or 0) >= 4:
        return "，" + _半句_流动[int(rng.integers(len(_半句_流动)))]
    return ""


def _并句(主: str, 内: str) -> str:
    """把「内态半句」并到主句尾：剥掉主句尾的重复标点，避免 `！。` / `。。`。"""
    主 = str(主 or "").rstrip()
    内 = str(内 or "")
    if not 内:
        return 主
    if not 主:
        return 内.lstrip("，。")
    while 主 and 主[-1] in "。！？!?，,；;":
        主 = 主[:-1]
    return 主 + 内