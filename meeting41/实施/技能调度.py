from 接口契约 import (熟练台阶秒, 熟练目标秒, 熟练初值秒)
from 时基 import 特征码

# 每档的目标拍时（ms）——与 技能原子.块拍数_档 同源：10 块 × (15,10,5,3) 拍 × 100ms
档拍时毫秒 = tuple(float(x) * 1000.0 for x in 熟练台阶秒)      # (15000, 10000, 5000, 3000)

挂档容差 = 1.5      # 中位 > 本档目标 × 此值 ⇒ 退档（如档2目标5000 ⇒ 中位>7500 才退）
基础次数 = 1        # 每轮基础练习次数（建议次数 = 基础次数 + 连续反弹）


class 技能调度:
    """台阶式训练调度器：确定性、只看历史、反弹即加练。"""

    def __init__(self, 台阶=熟练台阶秒, 目标秒: float = 熟练目标秒, 种子: int = 0,
                 禁用台阶: bool = False) -> None:
        self.台阶拍时 = tuple(float(x) * 1000.0 for x in 台阶)
        self.目标秒 = float(目标秒)
        self.种子 = int(种子)
        self.基础 = int(基础次数)
        # ★`禁用台阶=True` = 对照臂：**永不升档**（目标钉死在 15s）。
        #   用途：证明"台阶收紧"这件事**真的在起作用**，而不是装饰。
        #   （只把台阶值设平是不够的——档0 的 15000ms 同时满足平台阶目标，仍会连升三级。）
        self.禁用台阶 = bool(禁用台阶)
        self._技 = None                       # 可选绑定的 技能原子 实例
        self.台账s = {}                       # 技能名 → 状态

    # ── 绑定技能（升/退档时同步 技能原子.设档）──
    def 绑(self, 技能) -> None:
        self._技 = 技能
        return None

    # ── 状态 ──
    def _态(self, 技能名: str) -> dict:
        名 = str(技能名)
        if 名 not in self.台账s:
            self.台账s[名] = dict(
                技能名=名, 轮次列=[], 上轮中位=None, 最好毫秒=None, 中位毫秒=None,
                末次毫秒=None, 连续反弹=0, 反弹次数=0, 档=0, 目标毫秒=self.台阶拍时[0],
                加练次数=0, 未收敛次数=0)
        return self.台账s[名]

    def 建议次数(self, 技能名: str) -> int:
        """本轮该练几次 = 基础次数 + 连续反弹（**确定性**，只看历史）。"""
        s = self._态(技能名)
        return int(self.基础 + int(s["连续反弹"]))

    # ── 报一轮 ──
    def 报一轮(self, 技能名: str, 耗时列, 技能=None, 未收敛=None) -> dict:
        """把一轮的耗时列喂进来，更新状态并返回本轮报告（含契约要求的全部键）。"""
        s = self._态(技能名)
        列 = [float(x) for x in 耗时列]
        if not 列:
            raise ValueError("耗时列不得为空")
        最好 = float(min(列))
        中位 = float(statistics.median(列))
        末次 = float(列[-1])

        上轮中位 = s["上轮中位"]
        反弹 = bool(上轮中位 is not None and 中位 > float(上轮中位))
        趋势 = 0.0 if 上轮中位 is None else (中位 - float(上轮中位)) / float(上轮中位)

        if 反弹:
            s["连续反弹"] = int(s["连续反弹"]) + 1
            s["反弹次数"] = int(s["反弹次数"]) + 1
            加练 = True
        else:
            s["连续反弹"] = 0
            加练 = False

        # 历史最好（跨轮单调记，用于"达3秒"）
        s["最好毫秒"] = 最好 if s["最好毫秒"] is None else min(float(s["最好毫秒"]), 最好)

        # 档位：**只升不降**，且**每轮最多升 1 级**（台阶必须逐级走）。
        #   ★为什么必须"一轮一级"：若允许一轮内连升，档0 的 15000ms 就同时满足
        #     10s/5s/3s 三个目标 ⇒ 第 1 轮直接跳到档3，台阶形同虚设（实测如此）。
        #     一轮一级 ⇒ 必须真的把 15s 练到 10s，才谈 5s，再谈 3s——正是所有者要的台阶。
        #   ★档单调不减：档是"已经练到的熟练度"，一次打盹不该抹掉它（学习不能丢进度）；
        #     "反弹"只体现在**加练**上，不体现为退档。⇒ 目标毫秒单调不增 15→10→5→3。
        本档目标 = float(self.台阶拍时[int(s["档"])])
        if (not self.禁用台阶) and 最好 <= 本档目标 and int(s["档"]) < len(self.台阶拍时) - 1:
            s["档"] = int(s["档"]) + 1
        s["目标毫秒"] = float(self.台阶拍时[int(s["档"])])
        s["中位毫秒"], s["末次毫秒"], s["上轮中位"] = 中位, 末次, 中位
        if 未收敛 is not None:
            s["未收敛次数"] = int(s["未收敛次数"]) + int(bool(未收敛))

        # 同步到 技能原子：档变短 ⇒ 执行真的变快
        技 = 技能 or self._技
        同步档 = None
        if 技 is not None and hasattr(技, "设档"):
            同步档 = int(技.设档(int(s["档"])))

        台阶 = self._台阶序号(最好)
        达3秒 = bool(最好 <= self.目标秒 * 1000.0)
        sn = int(self.建议次数(技能名))       # ★须在更新连续反弹**之后**算
        报 = dict(轮次=len(s["轮次列"]) + 1, 次数=len(列),
                  最好毫秒=最好, 中位毫秒=中位, 末次毫秒=末次,
                  反弹=bool(反弹), 加练=bool(加练),
                  台阶=int(台阶), 达3秒=bool(达3秒), 趋势=float(趋势),
                  档=int(s["档"]), 目标毫秒=float(s["目标毫秒"]),
                  连续反弹=int(s["连续反弹"]), 加练次数=int(s["加练次数"]),
                  建议下一轮次数=int(sn), 同步技能档=同步档)
        if 加练:
            s["加练次数"] = int(s["加练次数"]) + 1
        s["轮次列"].append(dict(报))
        return 报

    def _台阶序号(self, 最好毫秒: float) -> int:
        """最好耗时达到的最高台阶序号：0=15s, 1=10s, 2=5s, 3=3s；未达 15s ⇒ -1。"""
        if 最好毫秒 > self.台阶拍时[0]:
            return -1
        序 = -1
        for i, 阈 in enumerate(self.台阶拍时):
            if 最好毫秒 <= float(阈) + 1e-9:
                序 = i
        return int(序)

    def 加练(self, 技能名: str) -> int:
        """追加训练次数（反弹惩罚）：连续反弹 +1，返回建议的下一轮次数。"""
        s = self._态(技能名)
        s["连续反弹"] = int(s["连续反弹"]) + 1
        s["加练次数"] = int(s["加练次数"]) + 1
        return int(self.建议次数(技能名))

    def 台账(self, 技能名: str = None) -> dict:
        if 技能名 is not None:
            s = self.台账s.get(str(技能名))
            if s is None:
                return dict(轮次列=[], 当前台阶=-1, 最好毫秒=None, 反弹次数=0)
            return dict(轮次列=[dict(r) for r in s["轮次列"]], 当前台阶=int(s["档"]),
                        最好毫秒=s["最好毫秒"], 反弹次数=int(s["反弹次数"]),
                        连续反弹=int(s["连续反弹"]), 目标毫秒=float(s["目标毫秒"]),
                        加练次数=int(s["加练次数"]), 建议下一轮次数=int(self.建议次数(技能名)))
        return {名: self.台账(名) for 名 in sorted(self.台账s)}

    def 特征码(self) -> str:
        """台账的确定性特征码（同输入序列 ⇒ 逐位同）。"""
        return 特征码({名: dict(轮次列=[dict(r) for r in s["轮次列"]],
                               连续反弹=int(s["连续反弹"]), 档=int(s["档"]))
                       for 名, s in sorted(self.台账s.items())})


