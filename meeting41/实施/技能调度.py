# 自测
# ══════════════════════════════════════════════════════════════════════

def 自测() -> dict:
    # ① 台阶递降：目标只收紧不放松，最终到 3s
    d = 技能调度()
    最好列 = [15000.0, 15000.0, 10000.0, 10000.0, 5000.0, 5000.0, 3000.0, 3000.0]
    逐轮 = []
    for x in 最好列:
        逐轮.append(d.报一轮("递降", [x, x, x]))
    档列 = [r["档"] for r in 逐轮]
    目标列 = [r["目标毫秒"] for r in 逐轮]
    目标不放松 = all(目标列[i] >= 目标列[i + 1] for i in range(len(目标列) - 1))
    档单调不减 = all(档列[i] <= 档列[i + 1] for i in range(len(档列) - 1))
    达3秒 = bool(逐轮[-1]["达3秒"])
    台阶到3 = bool(d.台账("递降")["当前台阶"] == 3)

    # ② 反弹：15s 起步 → 20s 倒退 ⇒ 反弹 & 加练 & 下一轮次数更多
    d2 = 技能调度()
    a1 = d2.报一轮("反弹", [15000.0, 14000.0, 13000.0])
    次1 = int(d2.建议次数("反弹"))
    a2 = d2.报一轮("反弹", [20000.0, 19000.0, 18000.0])
    次2 = int(d2.建议次数("反弹"))
    反弹对 = bool(a2["反弹"] is True and a2["加练"] is True and 次2 > 次1)

    # ③ 单次抖动**不**算反弹（口径：整轮用中位判）
    d3 = 技能调度()
    d3.报一轮("抖", [10000.0, 10000.0, 10000.0])
    b = d3.报一轮("抖", [10000.0, 10000.0, 30000.0])       # 末次暴涨但中位不变
    抖动不误报 = bool(b["反弹"] is False)

    # ④ 对照臂：目标永不收紧 ⇒ 最好停在 15s 量级
    d4 = 技能调度(台阶=(15.0, 15.0, 15.0, 15.0))
    对照最快 = None
    for _ in range(6):
        r = d4.报一轮("对照", [15000.0, 15000.0, 15000.0])
        对照最快 = r["最好毫秒"]
    对照臂停在15s = bool(对照最快 is not None and 对照最快 >= 15000.0)

    # ⑤ 确定性：同序列两遍 ⇒ 特征码逐位同
    def _跑():
        dd = 技能调度()
        for x in ([15000.0, 15000.0], [20000.0, 19000.0], [10000.0, 9000.0],
                  [5000.0, 5000.0], [3000.0, 3000.0]):
            dd.报一轮("确定", x)
        return dd
    甲, 乙 = _跑(), _跑()
    确定 = bool(甲.特征码() == 乙.特征码())

    # ⑥ 契约返回键齐全
    键 = set(逐轮[-1].keys())
    需 = {"轮次", "次数", "最好毫秒", "中位毫秒", "末次毫秒", "反弹", "加练",
          "台阶", "达3秒", "趋势"}
    键齐 = bool(需 <= 键)

    通过 = bool(目标不放松 and 档单调不减 and 达3秒 and 台阶到3 and 反弹对 and 抖动不误报
              and 对照臂停在15s and 确定 and 键齐)
    return dict(通过=通过, 目标不放松=目标不放松, 档单调不减=档单调不减,
                达3秒=达3秒, 台阶到3=台阶到3,
                反弹加练=dict(反弹对=反弹对, 次1=次1, 次2=次2,
                              第二轮=a2),
                抖动不误报=抖动不误报, 对照臂停在15s=对照臂停在15s,
                对照最快毫秒=对照最快, 确定性=确定, 契约键齐=键齐,
                档列=档列, 目标列=目标列)


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:                                         # noqa: BLE001
        pass
    果 = 自测()
    print(json.dumps(果, ensure_ascii=False, indent=1, default=str))
    print("[技能调度] 自测：%s" % ("PASS" if 果["通过"] else "FAIL"))
    raise SystemExit(0 if 果["通过"] else 1)
