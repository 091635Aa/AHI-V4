# -*- coding: utf-8 -*-
"""meeting41/实施/技能调度.py —— L2 技能调度（所有者口径的落地）。

━━━ 这一件要解决什么 ━━━
所有者原话：
  「学习操作需要过于流畅，比如说第一次15秒正式操作，第二次需要20秒相当于这次倒退
    要15秒，十秒，五秒，然后到三秒这种，这种就是一个训练」

⇒ 三条硬口径（**不得改**）：
  ① 台阶 15→10→5→3 秒：目标**只收紧不放松**（单调下降到 3s 下界）。
  ② **允许反弹**：整轮变慢（15→20 型）算倒退，**不判失败**。
  ③ **反弹即加练**：反弹 ⇒ `加练=True`，且**下一轮练习次数 > 本轮**。

━━━ 确定性律（这是"越练越快"的驱动，不是装饰）━━━
  状态：最好ms / 中位ms / 上轮中位 / 连续反弹 / 目标ms / 档
  一轮结束（耗时列）：
    最好 = min(列)；中位 = median(列)；末次 = 列[-1]
    反弹 = (中位 > 上轮中位)          # ★用"中位"判，单次抖动不算倒退
    连续反弹 = 连续反弹+1 if 反弹 else 0
    趋势 = (中位 − 上轮中位) / 上轮中位
    若 最好 ≤ 目标拍时: 档 += 1        # 达标才升档（15→10→5→3）
    若 中位 > 目标拍时 × 挂档容差: 档 −= 1   # 退步则退档（但**不**放松 目标：目标单调不增）
    目标 = 熟练台阶秒[档]
    建议下一轮次数 = 基础次数 + 连续反弹    # ★反弹 ⇒ 次数严格变多

  ★为什么"加练"不能挂在"档"上：若退档（档 2→1）会同轮把基础次数从 3 降到 2，
    与"反弹 ⇒ 加练"互相抵消，T2 判据就会挂。故此处**分离**：
      档 / 目标   → 反映"练到哪一级"（会随退步回退）
      建议次数    → 只由 连续反弹 驱动（反弹必然变多）
    两者都确定性，且各司其职。

━━━ 与 技能原子 的接线 ━━━
  调度器可选持有一个 `技能原子` 实例（`绑(技能)` 或 `报一轮(..., 技能=技)`）：
  升档时同步 `技.设档(档)`，于是 `技.当前序列()` 真的变短 ⇒ 执行耗时真的下降
  （档0=150拍=15000ms → 档3=30拍=3000ms）。这是"越练越快"的**物理实现**。

纪律：纯新增；不 import 器官；无全局随机态；不 import time（一切时间量走 时基 口径）。
"""
