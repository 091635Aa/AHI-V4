import 技能原子 as SK
import 技能调度 as SD
import 技能库 as KL
from 时基 import 拍钟, 特征码

技能名 = "合成_提交流程"


def 造技能(种子: int = 0, 名: str = 技能名) -> tuple:
    """造一把靶场 + 一个技能（10 块 × 核心三步，共 150 拍 = 15.000 秒）。"""
    世 = SK.靶场(种子=种子)
    技 = SK.技能原子(名, SK.造基础计划(世.元素列(), 种子=种子), 种子=种子)
    return 世, 技


def 校准基线(种子: int = 0, 名: str = 技能名, 档: int = 0) -> float:
    """量出该局面在 `档` 下的**基准耗时**（= 第一次正式操作的耗时）。

    ★为什么需要它：`档0` 的名义值是 15000ms（10 块 × 15 拍），但**实测会更高**——
      技能在**新局面的第一次操作**可能打空（对位残差 手抖系数/对位拍数 = 0.43px~9.3px，
      有时超过 3px 容差），于是触发一次「重新核对整屏」(+50 拍 = +5000ms)。
      这是 per-种子 确定的：种子0 恰好不打空(15000)，**种子4 第3块打空 ⇒ 基准 20000**。
      ⇒ 拿固定的 15000 当第一级门槛，会让"基准本来就慢"的种子**永远升不了档**（实测卡死 10 轮）。
      故台阶改按**该局面自己的基准**分级（台阶比例见 `台阶比例`），
      既保住所有者「15→10→5→3 秒」的原口径，又不会把种子的先天差异误判成"学不动"。
    """
    世, 技 = 造技能(种子=种子, 名=名)
    技.设档(int(档))
    世.开一轮(0)
    return float(技.执行(世, 拍钟())["耗时毫秒"])


# 台阶比例（相对该局面自己的基准）：1.0 → 0.667 → 0.333 → 0.2
#   对应所有者原口径 15s → 10s → 5s → 3s（3/15 = 0.2）。
台阶比例 = (1.0, 2.0 / 3.0, 1.0 / 3.0, 0.2)


def 造调度(基准毫秒: float, 目标秒: float = 3.0, 种子: int = 0, 禁用台阶: bool = False):
    """按基准耗时造一个调度器：台阶毫秒 = 基准 × 台阶比例（末级钉在 目标秒）。"""
    基 = float(基准毫秒)
    末 = float(目标秒) * 1000.0
    级 = [基 * r for r in 台阶比例]
    级[-1] = 末                       # 末级严格 = 目标秒（所有者口径 3 秒）
    级 = [min(x, 基) for x in 级]
    return SD.技能调度(台阶=tuple(x / 1000.0 for x in 级), 目标秒=目标秒,
                      种子=种子, 禁用台阶=禁用台阶)


def 跑训练(种子: int = 0, 轮数: int = 6, 名: str = 技能名,
           调度=None, 库路径: str = None, 存库: bool = False, 预置档: int = 0,
           校准: bool = True) -> dict:
    """跑 `轮数` 轮训练，返回 dict(轮列=..., 调度台账=..., 库=..., 特征码=...)。

    `轮列[i]` = 第 i+1 轮的 `报一轮` 报告（含 最好/中位/末次/反弹/加练/台阶/达3秒/趋势）。
    `预置档`：技能起手档位（默认 0 = 最慢）。
    `校准`：按该局面自己的 `档0` 基准分级台阶（见 `校准基线` 的说明）。
    """
    世, 技 = 造技能(种子=种子, 名=名)
    if int(预置档):
        技.设档(int(预置档))
    基准 = 校准基线(种子=种子, 名=名, 档=int(预置档)) if 校准 else 15000.0
    调 = 调度 or 造调度(基准, 种子=种子)
    调.绑(技)
    库 = KL.技能库(库路径 or os.path.join(HERE, "产物", "技能库.json"))
    库.登记(技)

    轮列 = []
    for i in range(int(轮数)):
        # ★所有轮次钉在同一局面（轮号 0）：这一件量的是**熟练度**，不是环境适应。
        #   若每轮换局面，目标位置会变 ⇒ 对位残差与"打空重做"次数跟着变 ⇒ 耗时被环境噪声
        #   污染（实测：第 8 轮换局面后 3000ms 反弹到 4100ms，被误判成"退步"）。
        #   环境适应是另一条轴（更换局面的泛化），不混进这条熟练度曲线。
        世.开一轮(0)
        次 = int(调.建议次数(名))
        耗时列, 果列 = [], []
        for _ in range(次):
            果 = 技.执行(世, 拍钟())
            耗时列.append(float(果["耗时毫秒"]))
            果列.append(dict(成功=bool(果["成功"]), 拍数=int(果["拍数"]),
                             耗时毫秒=float(果["耗时毫秒"]), 档=int(果["档"]),
                             重做=int(果["重做"]), 未收敛=bool(果.get("未收敛", False)),
                             目标不存在=list(果.get("目标不存在", []))))
        报 = 调.报一轮(名, 耗时列, 技能=技)
        报["逐次"] = 果列
        报["全成功"] = bool(all(g["成功"] for g in 果列))
        轮列.append(报)

    台账 = 调.台账(名)
    库.记台账(名, dict(轮次列=[dict(r) for r in 轮列],
                       最好毫秒=台账.get("最好毫秒"), 当前档=台账.get("当前台阶")))
    库果 = None
    if 存库:
        库果 = 库.存()

    列 = [dict(r) for r in 轮列]
    最好 = min([float(r["最好毫秒"]) for r in 列] or [float("inf")])
    return dict(通过=bool(all(r["全成功"] for r in 列)), 种子=int(种子), 技能名=名,
                轮列=列, 轮数=len(列),
                基准毫秒=float(基准), 最好毫秒=最好,
                缩比=float(最好 / 基准) if 基准 > 0 else None,
                达3秒=bool(最好 <= 3000.0),
                达目标=bool(any(r["达3秒"] for r in 列)),
                台阶序列=[int(r["台阶"]) for r in 列],
                档序列=[int(r["档"]) for r in 列],
                反弹轮=[i + 1 for i, r in enumerate(列) if r["反弹"]],
                加练轮=[i + 1 for i, r in enumerate(列) if r["加练"]],
                调度台账=台账, 库=库果, 库台账=库.台账(),
                特征码=特征码([[float(r["最好毫秒"]), float(r["中位毫秒"]),
                                int(r["档"]), bool(r["反弹"])] for r in 列]))


