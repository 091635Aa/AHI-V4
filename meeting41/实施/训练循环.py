# -*- coding: utf-8 -*-
"""meeting41/实施/训练循环.py —— L2 训练闭环（技能原子 × 技能调度 × 技能库）。

━━━ 它把"越练越快"真的跑出来 ━━━
一轮 = 在**同一局面**上把同一技能练 N 次（N = 调度.建议次数），量每次的耗时，交 `报一轮`。
调度按"最好 ≤ 本档目标 ⇒ 升档"推进；升档会**同步** `技能原子.设档()`，于是 `当前序列()`
真的变短 ⇒ 执行耗时真的下降（档0=150拍=15000ms → 档3=30拍=3000ms）。

★关键：变快**不是**改计时器，而是技能序列真的被压缩（`块拍数_档` 10 块 × 15/10/5/3 拍）。
★反弹（整轮中位变慢）**不判失败**，只触发加练（下一轮次数变多）。

纪律：纯新增；不 import 器官；不 import time；确定性（同种子 ⇒ 逐位同台账）。
"""
