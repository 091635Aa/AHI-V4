# ══════════════════════════════════════════════════════════════════════

def 自测() -> dict:
    # ① 主臂：8 轮训练，应逐级升档到 3 秒
    R = 8
    甲 = 跑训练(种子=0, 轮数=R)
    目标路径 = os.path.join(HERE, "产物", "_训练循环_自测.json")
    乙 = 跑训练(种子=0, 轮数=R, 库路径=目标路径, 存库=True)
    确定 = bool(甲["特征码"] == 乙["特征码"])

    达3 = bool(乙["达3秒"])
    达目标 = bool(乙["达目标"])
    缩比 = float(乙["缩比"])
    档升 = bool(max(乙["档序列"]) >= 3)
    最好 = float(乙["最好毫秒"])
    最好单调不增 = all(float(乙["轮列"][i]["最好毫秒"]) >= float(乙["轮列"][i + 1]["最好毫秒"]) - 1e-9
                    for i in range(len(乙["轮列"]) - 1))
    全成功 = bool(乙["通过"])

    # ② 反弹臂：人工把第 2 轮的耗时整体放大 ⇒ 中位变差 ⇒ 反弹 & 加练 & 次数更多
    调 = SD.技能调度(种子=0)
    调.报一轮("反弹臂", [15000.0, 14000.0, 13000.0])
    次1 = int(调.建议次数("反弹臂"))
    r2 = 调.报一轮("反弹臂", [20000.0, 19000.0, 18000.0])
    次2 = int(调.建议次数("反弹臂"))
    反弹加练 = bool(r2["反弹"] and r2["加练"] and 次2 > 次1)

    # ③ 对照臂（真 A/B）：两边**都从档0 起步、都用同一校准基准**，只差"台阶是否真的收紧"。
    #    主臂：台阶 基准→2/3→1/3→3s ⇒ 达标才升档 ⇒ 档跟上 ⇒ 技能序列变短 ⇒ 越来越快。
    #    对照：`禁用台阶=True`（永不升档）⇒ 档永远 0 ⇒ 停在基准耗时。
    #    ★判据 = 主臂档位 > 对照档位（收紧才有提升），并附两边的最好耗时对比。
    对照 = 跑训练(种子=0, 轮数=R,
                   调度=造调度(校准基线(种子=0), 禁用台阶=True),
                   库路径=os.path.join(HERE, "产物", "_训练循环_对照.json"), 校准=False)
    对照最好 = float(对照["最好毫秒"])
    对照档 = max(对照["档序列"]) if 对照["档序列"] else 0
    主臂档 = max(乙["档序列"]) if 乙["档序列"] else 0
    收紧带来提升 = bool(主臂档 > 对照档)

    # ④ 慢档必须真的慢（15→3 是机制，不是改计时器）
    世, 技 = 造技能(种子=0)
    各档 = {}
    for k in (0, 1, 2, 3):
        技.设档(k)
        世.开一轮(0)
        各档[k] = float(技.执行(世, 拍钟())["耗时毫秒"])
    档真变快 = bool(各档[0] == 15000.0 and 各档[3] == 3000.0
                 and all(各档[i] > 各档[i + 1] for i in range(3)))

    for p in (目标路径, os.path.join(HERE, "产物", "_训练循环_对照.json")):
        try:
            os.remove(p)
        except OSError:
            pass

    通过 = bool(达目标 and 档升 and 最好单调不增 and 全成功 and 反弹加练
              and 收紧带来提升 and 档真变快 and 确定)
    return dict(通过=通过, 达3秒=达3, 达目标=达目标, 缩比=缩比, 基准毫秒=乙["基准毫秒"],
                升到档3=档升, 最好毫秒=最好,
                最好单调不增=最好单调不增, 全成功=全成功,
                轮列=[dict(轮次=r["轮次"], 次数=r["次数"], 最好毫秒=r["最好毫秒"],
                           中位毫秒=r["中位毫秒"], 反弹=r["反弹"], 加练=r["加练"],
                           台阶=r["台阶"], 档=r["档"], 达3秒=r["达3秒"],
                           趋势=r["趋势"]) for r in 乙["轮列"]],
                档序列=乙["档序列"], 台阶序列=乙["台阶序列"],
                反弹加练=dict(通过=反弹加练, 次1=次1, 次2=次2),
                收紧带来提升=dict(通过=收紧带来提升, 主臂档=主臂档, 对照档=对照档,
                                  对照最好毫秒=对照最好),
                各档耗时毫秒=各档, 档真变快=档真变快, 确定性=确定)


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:                                         # noqa: BLE001
        pass
    果 = 自测()
    print(json.dumps(果, ensure_ascii=False, indent=1, default=str))
    print("[训练循环] 自测：%s" % ("PASS" if 果["通过"] else "FAIL"))
    raise SystemExit(0 if 果["通过"] else 1)
