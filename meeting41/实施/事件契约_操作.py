"""meeting41/实施/事件契约_操作.py —— L3 手事件 ↔ 正文/思考 的因果链 + **可失败**反例。

所有者原话（2026-10-08）：「边思考边操作边输出正文，……**思考流程和手上不会断**。」

━━━ 冻结契约（接口契约.py 第四节；本文件逐字照做）━━━
    class 事件契约_操作:
        def __init__(self, 窗拍: int = 2) -> None
        def 绑(self, 动作列, 正文项列, 思考项列) -> dict
            → dict(链=[dict(动作=,前文=,后文=,前置思考=,后置思考=,已绑=bool)],
                   孤立动作数=int, 未绑思考数=int, 覆盖率=float)
        def 不断证(self, 思考项列, 拍数) -> dict
            → dict(最大空隙拍=int, 空隙分布=dict, 结论=str)
        def 反例(self, 动词=None) -> dict          # ★三种情形，必须可判定

━━━ 三个量怎么算（全部从**传进来的真实时间线**算，不写死）━━━
  · 最大空隙拍  = 相邻思考项之间拍间隔的最大值（判据 ≤ 2）
  · 思考跨操作  = 有动作发生的拍里同样有思考项的拍数（判据 > 0）
  · 孤立动作数  = 前后 ±窗拍 内**无任何正文分片**的动作数（判据 == 0）
  · 覆盖率      = 窗内有正文的动作数 / 动作总数（手↔文同源，判据 ≥ 0.9；动作数为 0 时记 0.0）
                  链里每条动作的 `已绑` = 窗内**同时**有正文且有思考（因果链完整）

━━━ 三种反例（可失败性证明；判据_三层 T5 要「正常臂过 ∧ 三反例都不过」）━━━
  ① 抽思考  ：中间那一整段思考项抽掉（保留首尾各 1/4）   ⇒ 最大空隙拍 应超标
  ② 挪末尾  ：把所有动作整体后移到**正文末拍 + 窗拍 + 1** 之后 ⇒ 孤立动作数 应 > 0
  ③ 删正文  ：正文分片全删                          ⇒ 覆盖率 应下降（0.0）
  每个情形的 `结果` 都是可判定 dict：含 通过=False、判据=dict(...)、失败项=list。

━━━ 时间线来源（诚实登记）━━━
  反例 用**真实 输出流 跑出来的时间线**（同一层产物，来源="输出流"）；若 输出流 不可用，
  退回本文件内 `自造时间线()`（来源="自造"）。两者都在返回值 `时间线来源` 里如实标注。

━━━ 边界 ━━━
  本文件不 import 任何器官；手事件只作为**已发生记录的摘要**（动作列）被分析，不驱动真机。
"""
