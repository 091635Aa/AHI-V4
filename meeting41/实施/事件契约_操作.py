def _关键字接线自检(拍数: int = 10) -> dict:
    """按主程序最可能的写法接线：`契约.绑(**流.链())` / `契约.不断证(链["思考项列"], n)`。"""
    try:
        from 输出流 import 输出流
        流 = 输出流(种子=0)
        for _ in range(int(拍数)):
            流.一拍(输入s="接线自检")
        链 = 流.链()
        绑果 = 事件契约_操作(窗拍=2).绑(**链)
        断果 = 事件契约_操作(窗拍=2).不断证(链["思考项列"], int(拍数))
        return dict(通过=bool(set(绑果.keys()) >= {"链", "孤立动作数", "未绑思考数", "覆盖率"}
                             and set(断果.keys()) >= {"最大空隙拍", "空隙分布", "结论"}
                             and len(绑果["链"]) == len(链["动作列"])
                             and 断果["最大空隙拍"] <= 2),
                    绑键=sorted(绑果.keys()), 断键=sorted(断果.keys()),
                    链长=len(绑果["链"]), 动作数=len(链["动作列"]), 最大空隙拍=断果["最大空隙拍"])
    except Exception as e:
        return dict(通过=False, 错误=repr(e)[:160])


