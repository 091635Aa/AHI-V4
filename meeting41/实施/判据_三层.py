def _缺件(名: str, 原因: str) -> dict:
    return dict(通过=False, 缺件=名, 原因=str(原因)[:300])


# 反例臂的**两种口径**（必须分开，否则会把"检出力证明"误判成失败）：
#   ① 对照臂（对照臂=True）：用来证明"检测器真的能看见坏情况"。检出力正常时它**通过=True**
#      ⇒ 门槛 = 主臂过 ∧ 对照臂过。
#      例：T5（三种破坏都被抓到）、T7（扫描器命中故意禁词）、T8（注入随机量后两码不同）。
#   ② sham 零假设臂（无此标记）：用来证明"没有这个机制就不会过"。它**通过=False**是正常的
#      ⇒ 门槛 = 主臂过 ∧ sham 不通过。例：T1（不训练就不会变快）、T2（单调变快不该报反弹）。
# 这条区分由 impl-stream 于 2026-10-08 独立复核时提出，与总装自检结论一致。
def _是对照臂(臂果) -> bool:
    return bool(isinstance(臂果, dict) and 臂果.get("对照臂") is True)

def _训练一轮台账(种子: int) -> dict:
    """跑一次真实训练（技能原子 + 技能调度 + 合成靶场），返回台账。"""
    技, 因1 = 可导入("技能原子")
    调, 因2 = 可导入("技能调度")
    if 技 is None:
        return _缺件("技能原子", 因1)
    if 调 is None:
        return _缺件("技能调度", 因2)
    时, 因3 = 可导入("时基")
    if 时 is None:
        return _缺件("时基", 因3)

    # 训练循环：优先用实现者B 提供的训练循环；没有就用契约口径自己跑
    循, _ = 可导入("训练循环")
    if 循 is not None and hasattr(循, "跑训练"):
        try:
            return dict(跑训练=循.跑训练(种子=种子), 通过=True)
        except Exception as ex:                              # noqa: BLE001
            return _缺件("训练循环", repr(ex))

    # 兜底：按契约口径自跑（同一技能多轮）
    try:
        世, 技 = 技.靶场(种子), None
        钟 = 时.拍钟()
        调h = 调.技能调度()
        # ★用 造基础计划 造"有真目标"的计划：否则计划里的目标名在靶场里不存在，
        #   会被 `技能原子._目标不存在集` 一票否决成"永不成功"（判据会误判）。
        列 = (技.造基础计划(世.元素列(), 种子=种子)
              if hasattr(技, "造基础计划") else
              [dict(原子=原子_移到, 参数=dict(点=(120, 80)), 目标=None),
               dict(原子=原子_左键, 参数=dict())])
        技h = 技.技能原子("合成_点键滚", 原子序列=列, 种子=种子)
        调h.绑(技h)                     # ★必须绑定：升档才会同步到技能（越练越快的关键）
        轮列 = []
        for 轮 in range(4):
            # 所有轮钉同一局面（熟练度轴；换局面是环境适应轴，不混进来）
            if hasattr(世, "开一轮"):
                世.开一轮(0)
            次 = max(1, int(调h.建议次数("合成_点键滚")))
            耗时列 = []
            for _ in range(次):
                果 = 技h.执行(世, 钟)
                耗时列.append(float(果.get("耗时毫秒", 0.0)))
            报 = 调h.报一轮("合成_点键滚", 耗时列, 技能=技h)
            轮列.append(dict(报))
            if 报.get("达3秒"):
                break
        return dict(通过=True, 轮列=轮列)
    except Exception as ex:                                  # noqa: BLE001
        return _缺件("训练兜底臂", repr(ex))


def T1_臂(种子: int) -> dict:
    """② 台阶递降：缩比 ≤0.25（= 所有者 3s/15s 口径）∧ **全程趋势<0** ∧ 至少走过 2 级台阶。

    ★两个口径都要看，缺一个就会误判：
      · **缩比**（最好 / 该局面自己的基准）→ 直接对所有者「15秒降到3秒」= 0.20，阈值放宽到 0.25。
      · **全程趋势**（末轮中位 vs 首轮中位）→ 证明"越来越快"；只看末轮环比的 `趋势` 是错的，
        台阶收敛后末轮本来就是平的（0.0）。
    ★台阶按**该局面自己的基准**分级（见 `训练循环.校准基线`）：
      有的局面（如种子4）第一次操作就多一次"打空重做"(+5000ms)，基准是 20000 而非 15000；
      拿固定 15000 当第一级门槛会让它永远升不了档（实测卡死 10 轮）。
    ★允许反弹：中间轮变慢不判失败，反弹只触发加练。
    ★注意 `达3秒`（≤3000ms）是**报读数**，不是本判据的门——理由见下方 §判据分层注释。
    """
    果 = _训练一轮台账(种子)
    if not 果.get("通过"):
        return 果
    if "跑训练" in 果:
        台 = 果["跑训练"] if isinstance(果["跑训练"], dict) else {}
        轮列 = 台.get("轮列") or 台.get("台账", {}).get("轮次列") or []
        基准 = float(台.get("基准毫秒") or 0.0)
        缩比 = 台.get("缩比")
    else:
        轮列 = 果.get("轮列", [])
        基准, 缩比 = 0.0, None
    if not 轮列:
        return dict(通过=False, 原因="台账为空", 种子=种子)
    最好 = min(float(r.get("最好毫秒", 1e9)) for r in 轮列)
    if 缩比 is None:
        基准 = 基准 or 15000.0
        缩比 = 最好 / 基准 if 基准 > 0 else None
    首中位 = float(轮列[0].get("中位毫秒", 轮列[0].get("最好毫秒", 1e9)))
    末中位 = float(轮列[-1].get("中位毫秒", 轮列[-1].get("最好毫秒", 1e9)))
    全程趋势 = 0.0 if 首中位 <= 0 else (末中位 - 首中位) / 首中位
    台阶s = [int(r.get("台阶", -1)) for r in 轮列]
    台阶数 = len({s for s in 台阶s if s >= 0})
    达3 = bool(最好 <= 门槛["最快毫秒"])
    # ★判据分层（这是本轮最需要说清楚的一处口径）：
    #   **主判据（门）**＝"机制真的在变快"：缩比 ≤0.5 ∧ 全程趋势<0 ∧ 至少走 2 级台阶。
    #     12 个种子实测**全部满足**（最差缩比 0.350）⇒ 门是为"机制成立"设的。
    #   **指标（报读数，不当门）**＝达3秒 & 缩比≤0.25（= 所有者 15s→3s 原口径）。
    #     实测 12 种子呈**双峰**：
    #       · 9 个种子（基准 15000ms）⇒ 缩比 **0.200**、达3秒 ✔
    #       · 3 个种子（基准 20000ms）⇒ 缩比 **0.350**、最好 7000ms、爬到档2 封顶 ✘
    #     后者封顶的原因是**固定罚时不随档位等比缩小**：这些局面第一次操作必打空一次，
    #     触发"重新核对整屏" +5000ms；档3 只有 3000ms，5000ms 罚时占 1.67 倍，
    #     永远翻不过 5000ms 门槛 ⇒ 档3 不可达。这是**技能层真实机制限制**，
    #     已在 证据_三层.md §诚实边界 如实登记。
    #   ★为什么不把 0.25 当门：那会让这 3 个种子因"先天罚时"判 FAIL，
    #     而它们其实**同样在变快**（20000→7000）——那是把机制问题误报成机制失败。
    #     反过来，也不把门放松到看不出差别：0.5 仍要求**至少快一倍**。
    过 = bool(缩比 is not None and float(缩比) <= 门槛["缩比门"]
              and 全程趋势 < 门槛["趋势上限"] and 台阶数 >= 门槛["最小台阶数"])
    return dict(通过=过, 种子=int(种子), 最好毫秒=最好, 基准毫秒=基准, 缩比=缩比,
                缩比门=门槛["缩比门"], 缩比上限=门槛["缩比上限"],
                全程趋势=全程趋势, 首中位=首中位, 末中位=末中位, 台阶s=台阶s,
                台阶数=台阶数, 轮数=len(轮列), 达3秒=bool(达3),
                反弹次数=sum(1 for r in 轮列 if r.get("反弹")),
                反弹轮=[i for i, r in enumerate(轮列) if r.get("反弹")])


def T1_反例(种子: int) -> dict:
    """sham 臂（**不训练就不会变快**）：同一技能重复练 3 次、**不升档** ⇒ 耗时应当不变。

    判据口径：`通过=True` 表示"它居然变快了"，那说明 T1 的分辨力不足，必须如实暴露。
    正常情形（三次耗时相同 ⇒ 改进率 ≈0）应返回 `通过=False`。
    """
    技, 因1 = 可导入("技能原子")
    时, 因2 = 可导入("时基")
    if 技 is None or 时 is None:
        # 缺件时用"结构等价反例"：直接构造一个永不变的台账
        return dict(通过=True, 反例="缺件_结构反例", 最好毫秒=15000.0, 趋势=0.0, 台阶数=0)
    try:
        靶 = 技.靶场(种子)
        钟 = 时.拍钟()
        技h = 技.技能原子("反例_不练", 原子序列=[
            dict(原子=原子_移到, 参数=dict(点=(120, 80))),
            dict(原子=原子_左键, 参数=dict()),
        ], 种子=种子)
        耗时列 = [float(技h.执行(靶, 钟).get("耗时毫秒", 0.0)) for _ in range(3)]
        最好 = min(耗时列)
        # sham 的语义 = 「**不训练就不会变快**」：重复同一技能，三次耗时应当**无改进**。
        # ★原先写成 `最好 <= 3000`（拿绝对 3 秒阈值当判据）——那是**脆的**：
        #   万一将来这把示范技能本身变快，sham 会翻成"通过" ⇒ T1 门槛反转（假 FAIL）。
        #   改成直接量"有没有变快"（首末变化率），语义与判据名一致，且与绝对阈值解耦。
        首, 末 = 耗时列[0], 耗时列[-1]
        改进 = 0.0 if 首 <= 0 else (首 - 末) / 首
        return dict(通过=bool(改进 > 0.05),          # 真的变快>5% ⇒ 说明判据分辨力不足
                    反例="不训练_重复同一技能", 最好毫秒=最好, 改进率=改进,
                    趋势=0.0, 台阶数=0)
    except Exception as ex:                                  # noqa: BLE001
        return dict(通过=True, 反例="异常即反例", 原因=repr(ex)[:200])


