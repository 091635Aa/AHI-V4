# ── T3/T4 同时进行 ───────────────────────────────────────────────────

def _跑流(种子: int, 拍数: int = 60, 破坏: str = None) -> dict:
    """跑输出流 N 拍，返回 链 + 指标（可选破坏，供反例臂用）。"""
    流, 因1 = 可导入("输出流")
    契, 因2 = 可导入("事件契约_操作")
    时, 因3 = 可导入("时基")
    if 流 is None:
        return _缺件("输出流", 因1)
    if 契 is None:
        return _缺件("事件契约_操作", 因2)
    if 时 is None:
        return _缺件("时基", 因3)
    try:
        核 = None
        m核, _ = 可导入("算子_能力核")
        if m核 is not None and hasattr(m核, "能力核"):
            try:
                核 = m核.能力核(D=1024, 种子=种子)
            except Exception:                                # noqa: BLE001
                核 = None
        o = 流.输出流(能力核=核, 钟=时.拍钟(), 种子=种子)
        for i in range(int(拍数)):
            o.一拍(输入s=dict(拍=i))
        链 = o.链()
        指标 = o.链指标()
        思考列, 正文列, 动作列 = 链["思考项列"], 链["正文项列"], 链["动作列"]
        if 破坏 == "去思考":
            if len(思考列) > 4:
                思考列 = 思考列[:2] + 思考列[4:]               # 抽掉中间思考项
        elif 破坏 == "挪动作":
            if 动作列:
                末 = max([x.get("拍", 0) for x in list(思考列) + list(正文列)] or [0]) + 5
                动作列 = [dict(x, 拍=末) for x in 动作列]      # 动作整体挪到末尾
        elif 破坏 == "删正文":
            正文列 = []
        ev = 契.事件契约_操作()
        绑 = ev.绑(动作列, 正文列, 思考列)
        断 = ev.不断证(思考列, int(拍数))
        return dict(通过=True, 指标=指标, 绑=绑, 断=断, 拍数=int(拍数), 破坏=破坏,
                    思考数=len(思考列), 正文数=len(正文列), 动作数=len(动作列))
    except Exception as ex:                                  # noqa: BLE001
        return _缺件("输出流/事件契约_操作", repr(ex))


def T3_臂(种子: int) -> dict:
    """④ 最大空隙拍 ≤2 ∧ 思考跨操作 >0（"思考不会断"）。"""
    果 = _跑流(种子)
    if not 果.get("通过"):
        return 果
    大 = int(果["断"].get("最大空隙拍", 10 ** 9))
    跨 = int(果["指标"].get("思考跨操作", 0))
    过 = bool(大 <= 门槛["最大空隙拍"] and 跨 >= 门槛["思考跨操作下限"])
    return dict(通过=过, 种子=int(种子), 最大空隙拍=大, 思考跨操作=跨, 思考数=果["思考数"])


def T4_臂(种子: int) -> dict:
    """④ 孤立动作 =0 ∧ 覆盖率 ≥0.9（"手上和正文同源"）。"""
    果 = _跑流(种子)
    if not 果.get("通过"):
        return 果
    孤 = int(果["绑"].get("孤立动作数", 10 ** 9))
    覆 = float(果["绑"].get("覆盖率", 0.0))
    过 = bool(孤 == 0 and 覆 >= 门槛["覆盖率下限"])
    return dict(通过=过, 种子=int(种子), 孤立动作数=孤, 覆盖率=覆, 动作数=果["动作数"])


def T5_臂(种子: int) -> dict:
    """④ 三种反例**都不过** ⇒ 判据本身可失败。"""
    契, 因 = 可导入("事件契约_操作")
    if 契 is None:
        return _缺件("事件契约_操作", 因)
    try:
        ev = 契.事件契约_操作()
        正常 = _跑流(种子)
        if not 正常.get("通过"):
            return dict(通过=False, 原因="正常臂本身不可用：" + str(正常.get("原因"))[:200])
        果s = {}
        for 破坏 in ("去思考", "挪动作", "删正文"):
            果s[破坏] = _跑流(种子, 破坏=破坏)
        # 每条反例的"坏"：与正常臂比，指标必须变差
        好 = {}
        好["去思考"] = bool(果s["去思考"].get("通过")
                          and int(果s["去思考"]["断"].get("最大空隙拍", 0))
                          > 门槛["最大空隙拍"])
        好["挪动作"] = bool(果s["挪动作"].get("通过")
                          and int(果s["挪动作"]["绑"].get("孤立动作数", 0)) > 0)
        好["删正文"] = bool(果s["删正文"].get("通过")
                          and float(果s["删正文"]["绑"].get("覆盖率", 1.0))
                          < float(正常["绑"].get("覆盖率", 0.0)))
        # T5 的"通过" = 三条反例都被抓到（= 判据有分辨力）
        return dict(通过=all(好.values()), 对照臂=True, 种子=int(种子), 逐反例=好,
                    正常_最大空隙拍=正常["断"].get("最大空隙拍"),
                    正常_孤立=正常["绑"].get("孤立动作数"),
                    正常_覆盖=正常["绑"].get("覆盖率"),
                    反例_最大空隙拍=果s["去思考"].get("断", {}).get("最大空隙拍"),
                    反例_孤立=果s["挪动作"].get("绑", {}).get("孤立动作数"),
                    反例_覆盖=果s["删正文"].get("绑", {}).get("覆盖率"))
    except Exception as ex:                                  # noqa: BLE001
        return _缺件("T5", repr(ex))


def T5_反例(种子: int) -> dict:
    """T5 **对照臂**：不做破坏时，三条"坏"都不该成立 ⇒ 若成立说明指标本身乱动（过敏感）。"""
    正常 = _跑流(种子)
    if not 正常.get("通过"):
        return dict(通过=False, 对照臂=True, 反例="正常臂缺件", 原因=str(正常.get("原因"))[:200])
    好 = bool(int(正常["断"].get("最大空隙拍", 0)) <= 门槛["最大空隙拍"]
             and int(正常["绑"].get("孤立动作数", 1)) == 0)
    return dict(通过=bool(好), 对照臂=True, 反例="未破坏", 说明="未破坏却已超标 ⇒ 指标失效")


