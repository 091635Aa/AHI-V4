def 特征码(对象) -> str:
    """确定性特征码（键排序 + 紧凑分隔符）——与既有 时基/测量台 同口径。"""
    def _可序列(x):
        if hasattr(x, "tolist"):
            return _可序列(x.tolist())
        if isinstance(x, dict):
            return {str(k): _可序列(v) for k, v in sorted(x.items(), key=lambda kv: str(kv[0]))}
        if isinstance(x, (list, tuple)):
            return [_可序列(i) for i in x]
        if isinstance(x, (set, frozenset)):
            return sorted(_可序列(i) for i in x)
        if isinstance(x, (str, bool, int, float)) or x is None:
            return x
        return str(x)
    return hashlib.sha256(json.dumps(_可序列(对象), ensure_ascii=False, sort_keys=True,
                                     separators=(",", ":"), default=str).encode("utf-8")
                          ).hexdigest()


def 可导入(名: str):
    """尝试导入；成功返回模块，失败返回 (None, 原因)。"""
    try:
        return __import__(名), None
    except Exception as ex:                                  # noqa: BLE001
        return None, "%s: %s" % (type(ex).__name__, ex)


